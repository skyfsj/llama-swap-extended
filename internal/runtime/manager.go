// Manager owns the runtime lifecycle for all configured runtimes.
//
// Locking model: mu is the manager-wide state lock guarding m.status,
// m.definitions, m.providers and the persisted-state read-modify-write
// sections. Lifecycle operations (Stage/Activate/Check) additionally hold a
// per-runtime operation lock (opLocks) for their whole duration, but release
// mu during the long provider sections — downloads, builds, verify/health
// probes — so other runtimes, the control plane (FlushControlUpdate,
// Configure, Rollback) and model pre-start gates are never blocked behind a
// multi-hour compile or a 90-second probe. Lock order is strictly
// opLock(name) → mu; nothing may acquire an op lock while holding mu. Reads
// stay available at all times through statusView. History note: mu was held
// across provider work until 2026-09; the per-runtime split above replaced
// it, and the earlier H1 apply/activation deadlock is additionally guarded
// by the lock-free control-update queue.
type Manager struct {
	root      string
	providers map[string]Provider
	mu        sync.Mutex
	// opLocks serializes lifecycle operations (Stage/Activate/Check) per
	// runtime name. The map itself is guarded by mu; the mutexes are taken
	// BEFORE mu and never while mu is held — lifecycle operations release mu
	// during provider work, so taking an op lock under mu would deadlock
	// against those operations' locked sections.
	opLocks          map[string]*sync.Mutex
	callbackMu       sync.RWMutex
	switchBefore     RuntimeSwitchHook
	switchAfter      RuntimeSwitchHook
	versionProbe     func(name, version string) (protected bool, reason string)
	operationMu      sync.RWMutex
	operationSink    func(Operation)
	idle             func() bool
	idleSince        time.Time
	runtimeIdle      map[string]func() bool
	runtimeIdleSince map[string]time.Time
	buildWhileBusy   bool
	progress         func(swaputil.BackendProgressEvent)
	now              func() time.Time
	status           map[string]Status
	// operationLogs captures the most recent build/install output per runtime
	// so an operator opening the log panel mid-build (or after it finished)
	// still sees the output, not just the clients that were connected while
	// the log events streamed. Guarded by logBufMu.
	logBufMu sync.Mutex
	logBufs  map[string]*runtimeOperationLog
	// statusView is an immutable read snapshot. Runtime staging intentionally
	// holds mu across provider work to serialize filesystem transitions, but
	// control-plane reads must remain available while a provider downloads or
	// compiles a candidate.
	statusView  atomic.Value // stores []Status
	definitions map[string]Definition
	// controlUpdateMu guards the pending control update queued by the
	// configuration layer. QueueControlUpdate never takes m.mu: an in-flight
	// activation holds m.mu while its switch hook waits for the apply to
	// finish, so the queue side of the pair must stay lock-free or the pair
	// deadlocks. The loop side (FlushControlUpdate) is the only path that
	// applies queued state under m.mu.
	controlUpdateMu         sync.Mutex
	pendingControlUpdate    ControlUpdate
	hasPendingControlUpdate bool
	controlUpdateSignal     chan struct{}
}

func NewManager(root string, providers map[string]Provider) (*Manager, error) {
	if strings.TrimSpace(root) == "" {
		return nil, errors.New("runtime root is required")
	}
	if !filepath.IsAbs(root) {
		return nil, errors.New("runtime root must be absolute")
	}
	if err := rejectSymlinkPath(root); err != nil {
		return nil, fmt.Errorf("runtime root: %w", err)
	}
	if err := os.MkdirAll(root, 0o750); err != nil {
		return nil, fmt.Errorf("create runtime root: %w", err)
	}
	m := &Manager{root: root, providers: providers, now: time.Now, status: make(map[string]Status), definitions: make(map[string]Definition), runtimeIdle: make(map[string]func() bool), runtimeIdleSince: make(map[string]time.Time), controlUpdateSignal: make(chan struct{}, 1), logBufs: make(map[string]*runtimeOperationLog)}
	m.statusView.Store([]Status{})
	if err := m.load(); err != nil {
		return nil, err
	}
	return m, nil
}

func (m *Manager) SetIdleProbe(probe func() bool) {
	if m != nil {
		m.callbackMu.Lock()
		defer m.callbackMu.Unlock()
		m.idle = probe
	}
}

// SetRuntimeIdleProbe installs an idle probe for one runtime. It falls back to
// the global probe when no runtime-specific callback is registered. This lets
// dependencies such as LMCache add their own model-reference/process gates
// without weakening the generic inference-plane idle contract.
func (m *Manager) SetRuntimeIdleProbe(name string, probe func() bool) {
	if m == nil {
		return
	}
	name = strings.TrimSpace(name)
	if name == "" {
		return
	}
	m.callbackMu.Lock()
	defer m.callbackMu.Unlock()
	if m.runtimeIdle == nil {
		m.runtimeIdle = make(map[string]func() bool)
	}
	if probe == nil {
		delete(m.runtimeIdle, name)
		return
	}
	m.runtimeIdle[name] = probe
}

// SetProvider replaces one provider used by future checks and stages. Providers
// are normally installed during Server construction, but configuration reloads
// may change source allowlists or container registries while the automatic
// update loop is already running. Keep the map mutation behind Manager.mu so a
// reload cannot race the loop's provider lookup.
func (m *Manager) SetProvider(kind string, provider Provider) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	kind = strings.TrimSpace(kind)
	if err := validateName(kind); err != nil {
		return fmt.Errorf("runtime provider kind: %w", err)
	}
	if isNilProvider(provider) {
		return fmt.Errorf("runtime provider %q is nil", kind)
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.providers == nil {
		m.providers = make(map[string]Provider)
	}
	m.providers[kind] = provider
	return nil
}

// SetActivationHooks installs the optional process-lifecycle bridge used by an
// embedding server. The hooks are copied under the callback lock so callers can
// replace them while an update loop is running. A nil hook disables that phase.
func (m *Manager) SetActivationHooks(before, after RuntimeSwitchHook) {
	if m == nil {
		return
	}
	m.callbackMu.Lock()
	m.switchBefore = before
	m.switchAfter = after
	m.callbackMu.Unlock()
}

// SetVersionProtectionProbe installs the deletion-protection bridge used by
// version pruning. The manager protects current/previous/pinned by itself;
// the probe carries the embedding server's knowledge: models that run from
// or pin a concrete version, and live dependency counts the manager cannot
// see (e.g. the LMCache server's model references or an in-flight update).
// A protected version is skipped, never deleted.
func (m *Manager) SetVersionProtectionProbe(probe func(name, version string) (protected bool, reason string)) {
	if m == nil {
		return
	}
	m.callbackMu.Lock()
	m.versionProbe = probe
	m.callbackMu.Unlock()
}

func (m *Manager) versionProtected(name, version string) (bool, string) {
	if m == nil {
		return false, ""
	}
	m.callbackMu.RLock()
	probe := m.versionProbe
	m.callbackMu.RUnlock()
	if probe == nil {
		return false, ""
	}
	return probe(name, version)
}

func (m *Manager) activationHooks() (RuntimeSwitchHook, RuntimeSwitchHook) {
	if m == nil {
		return nil, nil
	}
	m.callbackMu.RLock()
	before, after := m.switchBefore, m.switchAfter
	m.callbackMu.RUnlock()
	return before, after
}

// SetProgress installs the common BackendProgress publisher. It is normally
// configured once during server construction; runtime operations then emit
// state transitions without depending on the HTTP layer.
func (m *Manager) SetProgress(publisher func(swaputil.BackendProgressEvent)) {
	if m != nil {
		m.callbackMu.Lock()
		defer m.callbackMu.Unlock()
		m.progress = publisher
	}
}

// SetOperationSink installs an optional durable operation sink. The file
// journal remains the source of truth for crash recovery; the sink mirrors
// each successfully appended transition into a control-plane store so the
// UI can query operation history without parsing runtime directories. The
// callback is invoked synchronously after the journal fsync and must not call
// back into the manager.
func (m *Manager) SetOperationSink(sink func(Operation)) {
	if m == nil {
		return
	}
	m.operationMu.Lock()
	m.operationSink = sink
	m.operationMu.Unlock()
}

func (m *Manager) emitProgress(name, phase string, progress float64, message string, progressErr error) {
	m.emitProgressBytes(name, phase, progress, 0, 0, message, progressErr)
}

func (m *Manager) emitProgressBytes(name, phase string, progress float64, completed, total int64, message string, progressErr error) {
	if m == nil {
		return
	}
	m.callbackMu.RLock()
	publisher := m.progress
	m.callbackMu.RUnlock()
	if publisher == nil {
		return
	}
	if progress < 0 {
		progress = 0
	}
	if progress > 1 {
		progress = 1
	}
	event := swaputil.BackendProgressEvent{Runtime: name, Phase: phase, Progress: progress, Completed: completed, Total: total, Message: message}
	if progressErr != nil {
		event.Error = progressErr.Error()
	}
	publisher(event)
}

// runtimeOperationLogBufferLimit bounds the captured output per runtime.
// Compiler and pip output for a full vLLM wheel build can reach megabytes;
// the tail is what an operator diagnosing a build needs, mirroring the
// bounded diagnostic carried by failed operations.
const runtimeOperationLogBufferLimit = 256 << 10

// runtimeOperationLog captures one operation's streamed build/install output
// per runtime. A new operation ID replaces the previous buffer, so the
// capture always reflects the latest (or currently running) operation.
type runtimeOperationLog struct {
	operationID string
	output      []byte
}

func (m *Manager) appendRuntimeOperationLog(name, operationID string, output []byte) {
	if m == nil || name == "" || len(output) == 0 {
		return
	}
	m.logBufMu.Lock()
	defer m.logBufMu.Unlock()
	buf := m.logBufs[name]
	if buf == nil || buf.operationID != operationID {
		buf = &runtimeOperationLog{operationID: operationID}
		m.logBufs[name] = buf
	}
	buf.output = append(buf.output, output...)
	if len(buf.output) > runtimeOperationLogBufferLimit {
		buf.output = append([]byte(nil), buf.output[len(buf.output)-runtimeOperationLogBufferLimit:]...)
	}
}

// RuntimeOperationLog returns the captured output of the runtime's most
// recent operation (download, build, install) plus the operation ID it
// belongs to. The capture survives operation completion so a log panel opened
// afterwards still shows what happened; it is replaced when the next
// operation starts.
func (m *Manager) RuntimeOperationLog(name string) (string, string) {
	if m == nil {
		return "", ""
	}
	m.logBufMu.Lock()
	defer m.logBufMu.Unlock()
	buf := m.logBufs[name]
	if buf == nil {
		return "", ""
	}
	return buf.operationID, string(buf.output)
}

// EmitRuntimeLog is the exported seam for feeding build/install output into a
// runtime's operation log capture and progress stream. Built-in providers
// reach the same path through the context-attached log callback; embedders
// that run builds outside those providers use this.
func (m *Manager) EmitRuntimeLog(name, operationID, stream string, output []byte) {
	m.emitRuntimeLog(name, operationID, stream, output)
}

func (m *Manager) emitRuntimeLog(name, operationID, stream string, output []byte) {
	if m == nil || len(output) == 0 {
		return
	}
	m.appendRuntimeOperationLog(name, operationID, output)
	m.callbackMu.RLock()
	publisher := m.progress
	m.callbackMu.RUnlock()
	if publisher == nil {
		return
	}
	publisher(swaputil.BackendProgressEvent{
		Runtime:      name,
		OperationID:  operationID,
		Phase:        "log",
		OutputStream: stream,
		Output:       string(output),
	})
}

// SetBuildWhileBusy controls whether staging may download/build while the
// inference plane is busy. The safe default is false: a busy runtime can be
// checked, but an update is left waiting until the idle probe reports that it
// is safe to consume resources. This does not affect activation, which always
// requires an idle runtime.
func (m *Manager) SetBuildWhileBusy(allow bool) {
	if m != nil {
		m.callbackMu.Lock()
		defer m.callbackMu.Unlock()
		m.buildWhileBusy = allow
	}
}

// idleNow snapshots the optional idle probe before invoking it. The probe is
// supplied by the server and may itself inspect other mutable state, so never
// hold Manager or callbackMu while calling into that external function.
func (m *Manager) idleNow() bool {
	return m.idleNowFor("")
}

func (m *Manager) idleNowFor(name string) bool {
	if m == nil {
		return false
	}
	m.callbackMu.RLock()
	probe := m.idle
	if name != "" {
		if runtimeProbe, ok := m.runtimeIdle[name]; ok {
			probe = runtimeProbe
		}
	}
	m.callbackMu.RUnlock()
	return probe == nil || probe()
}

func (m *Manager) buildWhileBusyAllowed() bool {
	if m == nil {
		return false
	}
	m.callbackMu.RLock()
	defer m.callbackMu.RUnlock()
	return m.buildWhileBusy
}

// opLock returns the per-runtime lifecycle operation mutex. Callers must
// acquire it BEFORE m.mu and never while m.mu is held: Stage/Activate/Check
// hold it for their whole operation while releasing m.mu during provider
// work, so a path that waits for the op lock under m.mu would deadlock
// against those operations' locked sections.
func (m *Manager) opLock(name string) *sync.Mutex {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.opLocks == nil {
		m.opLocks = make(map[string]*sync.Mutex)
	}
	lock, ok := m.opLocks[name]
	if !ok {
		lock = &sync.Mutex{}
		m.opLocks[name] = lock
	}
	return lock
}

func (m *Manager) Root() string {
	if m == nil {
		return ""
	}
	return m.root
}

func (m *Manager) runtimeDir(name string) (string, error) {
	if m == nil {
		return "", errors.New("runtime manager is nil")
	}
	if err := validateName(name); err != nil {
		return "", err
	}
	dir := filepath.Join(m.root, name)
	if filepath.Clean(dir) != filepath.Join(filepath.Clean(m.root), name) {
		return "", errors.New("runtime path escapes root")
	}
	// Runtime directories are manager-owned boundaries.  A directory entry
	// replaced with a symlink must not be followed by Stage/Register/rollback
	// writes, otherwise an operator or a compromised process could redirect
	// runtime state outside the configured root.  Missing paths are allowed so
	// the normal creation path can still initialize a new runtime.
	if err := rejectSymlinkPath(dir); err != nil {
		return "", fmt.Errorf("runtime path: %w", err)
	}
	return dir, nil
}

func validateName(name string) error {
	if name == "" || name == "." || name == ".." || len(name) > 255 || strings.ContainsAny(name, "/\\") || strings.IndexByte(name, 0) >= 0 {
		return fmt.Errorf("invalid runtime name %q", name)
	}
	for _, r := range name {
		// Runtime and version names are used as directory components and are
		// surfaced in logs/UI. Reject Unicode whitespace and format characters
		// as well as ASCII controls so visually blank or zero-width names cannot
		// create confusing paths or colliding control-plane entries.
		if unicode.IsSpace(r) || unicode.IsControl(r) || unicode.Is(unicode.Cf, r) {
			return fmt.Errorf("invalid runtime name %q", name)
		}
	}
	return nil
}

// isNilProvider handles both a nil Provider interface and an interface that
// contains a typed-nil pointer/map/etc. Providers are supplied by embedders
// and configuration wiring, so treating a typed-nil value as registered would
// otherwise defer a panic until a long-running operation calls its methods.
func isNilProvider(provider Provider) bool {
	if provider == nil {
		return true
	}
	value := reflect.ValueOf(provider)
	switch value.Kind() {
	case reflect.Chan, reflect.Func, reflect.Interface, reflect.Map, reflect.Pointer, reflect.Slice:
		return value.IsNil()
	default:
		return false
	}
}

// validateVersion deliberately uses the same single-component policy as
// runtime names. Version strings are used as directory names and map keys;
// accepting separators and then replacing them in safeVersion would make
// distinct versions collide (for example a/b and a\\b) and could turn a
// malformed manifest into an apparently valid activation target.
func validateVersion(version string) error {
	if strings.TrimSpace(version) != version {
		return fmt.Errorf("invalid runtime version %q", version)
	}
	if err := validateName(version); err != nil {
		return fmt.Errorf("invalid runtime version %q", version)
	}
	return nil
}

func (m *Manager) load() error {
	entries, err := os.ReadDir(m.root)
	if err != nil {
		return fmt.Errorf("read runtime root: %w", err)
	}
	for _, entry := range entries {
		if !entry.IsDir() || strings.HasPrefix(entry.Name(), ".") {
			continue
		}
		name := entry.Name()
		state, err := m.readState(name)
		if err != nil {
			// A process can be terminated after the version directory and its
			// current pointer are durable but before state.json is renamed. Use
			// the per-version manifest to reconstruct that state; this keeps a
			// valid runtime serving after restart instead of forcing a needless
			// rebuild. If no manifest is available, expose a degraded status and
			// leave any unsafe pointers for recoverPointers to remove on the next
			// successful state load.
			if recovered, ok := m.recoverStateWithoutState(name); ok {
				state = recovered
				if err := m.writeState(name, state); err != nil {
					m.setStatusLocked(name, Status{Name: name, State: StateDegraded, LastError: err.Error(), UpdatedAt: m.now()})
					continue
				}
			} else {
				// Even a malformed/missing state file must not leave a dangling
				// current or previous symlink behind. recoverPointers validates and
				// removes only manager-owned unsafe pointers; a valid pointer is
				// preserved for an operator to inspect alongside the degraded status.
				status := Status{Name: name, State: StateDegraded, LastError: err.Error(), UpdatedAt: m.now()}
				_, changed := m.recoverPointers(name, &status, make(map[string]Manifest))
				if changed {
					// There is no trustworthy state to write yet; the pointer cleanup
					// itself is durable through the directory fsync in recovery.
					_ = syncDir(filepath.Join(m.root, name))
				}
				m.setStatusLocked(name, status)
				continue
			}
		}
		if state.Versions == nil {
			state.Versions = make(map[string]Manifest)
		}
		orphans := m.adoptOrphanVersions(name, &state)
		status := state.Status
		if status.Name == "" {
			status.Name = name
		}
		recovered, changed := m.recoverPointers(name, &status, state.Versions)
		if orphans > 0 {
			changed = true
		}
		if recovered {
			// A process can be terminated between the journal write and the
			// final state write. A valid current pointer is authoritative; do
			// not leave an interrupted BUILDING/ACTIVATING state blocking the
			// next operation after restart.
			if status.State == StateStaging || status.State == StateDownloading || status.State == StateBuilding || status.State == StateVerifying || status.State == StateActivating || status.State == StateHealthCheck || status.State == StateRollback {
				status.State = StateActive
				status.LastError = "recovered interrupted runtime operation"
				changed = true
			}
		}
		status.UpdatedAt = m.now()
		if status.Current != "" {
			for version, manifest := range state.Versions {
				if safeVersion(version) == safeVersion(status.Current) {
					status.Source = manifest.Source
					status.Mode = manifestMode(manifest)
					break
				}
			}
		}
		state.Status = status
		m.setStatusLocked(name, status)
		if changed {
			// The in-memory status is published either way, so a discarded error
			// here means a read-only runtime root repeats the same recovery on
			// every restart with nothing recording why.
			if err := m.writeState(name, state); err != nil {
				log.Printf("runtime: persist recovered state for %s: %v", name, err)
			}
		}
	}
	return nil
}

// recoverStateWithoutState rebuilds the minimal persistent state from a
// durable current/previous pointer and the manifest written into each version
// directory before the pointer can be activated. It is intentionally
// conservative: a pointer without a valid manifest is not advertised.
func (m *Manager) recoverStateWithoutState(name string) (persistedState, bool) {
	dir, err := m.runtimeDir(name)
	if err != nil {
		return persistedState{}, false
	}
	current, err := readLink(filepath.Join(dir, "current"))
	if err != nil || validVersionDir(dir, current) != nil {
		return persistedState{}, false
	}
	currentManifest, err := readManifest(filepath.Join(dir, "versions", current, "manifest.json"))
	if err != nil || currentManifest.Validate() != nil {
		return persistedState{}, false
	}
	status := Status{Name: name, Kind: currentManifest.Kind, Mode: manifestMode(currentManifest), Source: currentManifest.Source, Current: currentManifest.Version, State: StateActive, UpdatedAt: m.now()}
	versions := map[string]Manifest{currentManifest.Version: currentManifest}
	if previous, previousErr := readLink(filepath.Join(dir, "previous")); previousErr == nil && validVersionDir(dir, previous) == nil {
		if manifest, manifestErr := readManifest(filepath.Join(dir, "versions", previous, "manifest.json")); manifestErr == nil && manifest.Validate() == nil {
			versions[manifest.Version] = manifest
			status.Previous = manifest.Version
		}
	}
	return persistedState{Status: status, Versions: versions}, true
}

// adoptOrphanVersions folds version directories that exist on disk with a
// valid manifest but are missing from the state ledger back into the ledger,
// and returns how many were adopted. A process can be terminated after the
// versions/<v> directory becomes durable but before the state write commits
// (the Stage crash window). An unadopted orphan makes the next Stage of the
// same version redo the entire download/build and then fail the commit guard
// with "already installed" — on every automatic update pass.
func (m *Manager) adoptOrphanVersions(name string, state *persistedState) int {
	dir, err := m.runtimeDir(name)
	if err != nil {
		return 0
	}
	entries, err := os.ReadDir(filepath.Join(dir, "versions"))
	if err != nil {
		return 0
	}
	adopted := 0
	for _, entry := range entries {
		if !entry.IsDir() || strings.HasPrefix(entry.Name(), ".") {
			continue
		}
		version := entry.Name()
		known := false
		for key := range state.Versions {
			if safeVersion(key) == safeVersion(version) {
				known = true
				break
			}
		}
		if known {
			continue
		}
		manifest, manifestErr := readManifest(filepath.Join(dir, "versions", version, "manifest.json"))
		if manifestErr != nil || manifest.Validate() != nil || safeVersion(manifest.Version) != safeVersion(version) {
			continue
		}
		state.Versions[manifest.Version] = manifest
		adopted++
	}
	return adopted
}

// recoverPointers validates current/previous symlinks before exposing a
// runtime after restart. Dangling or externally-targeted pointers are removed
// rather than retained as an unsafe active runtime. A valid current pointer is
// returned separately so callers can recover an interrupted state transition.
func (m *Manager) recoverPointers(name string, status *Status, versions map[string]Manifest) (bool, bool) {
	dir, err := m.runtimeDir(name)
	if err != nil {
		return false, false
	}
	changed := false
	current, currentErr := readLink(filepath.Join(dir, "current"))
	if currentErr == nil {
		if statErr := validVersionDir(dir, current); statErr != nil {
			_ = os.Remove(filepath.Join(dir, "current"))
			if status.Current != "" {
				status.Current = ""
			}
			status.State = StateDegraded
			status.LastError = "current runtime pointer is dangling"
			changed = true
		} else {
			// The symlink is the crash-safe source of truth. If state.json was
			// written just before a pointer rename (or was edited by an older
			// version), do not retain a stale/logically unsafe current value.
			if status.Current != current {
				status.Current = current
				changed = true
			}
			if _, ok := versions[status.Current]; !ok {
				for version, manifest := range versions {
					if safeVersion(version) == safeVersion(current) {
						versions[status.Current] = manifest
						break
					}
				}
			}
		}
	} else if !errors.Is(currentErr, os.ErrNotExist) {
		_ = os.Remove(filepath.Join(dir, "current"))
		status.Current = ""
		status.State = StateDegraded
		status.LastError = "current runtime pointer is invalid: " + currentErr.Error()
		changed = true
	} else if status.Current != "" {
		status.State = StateDegraded
		status.LastError = "current runtime pointer is missing"
		changed = true
	}
	previous, previousErr := readLink(filepath.Join(dir, "previous"))
	if previousErr == nil {
		if statErr := validVersionDir(dir, previous); statErr != nil {
			_ = os.Remove(filepath.Join(dir, "previous"))
			status.Previous = ""
			changed = true
		} else if status.Previous != previous {
			status.Previous = previous
			changed = true
		}
	} else if !errors.Is(previousErr, os.ErrNotExist) {
		_ = os.Remove(filepath.Join(dir, "previous"))
		status.Previous = ""
		changed = true
	}
	// Staging directories are never valid versions. They can remain after a
	// forced termination, so clean only the manager-owned temporary entries.
	if entries, readErr := os.ReadDir(filepath.Join(dir, "versions")); readErr == nil {
		for _, entry := range entries {
			if entry.IsDir() && strings.HasPrefix(entry.Name(), ".staging-") {
				_ = os.RemoveAll(filepath.Join(dir, "versions", entry.Name()))
				changed = true
			}
		}
	}
	return currentErr == nil && status.Current != "", changed
}

func (m *Manager) readState(name string) (persistedState, error) {
	dir, err := m.runtimeDir(name)
	if err != nil {
		return persistedState{}, err
	}
	statePath := filepath.Join(dir, "state.json")
	if err := rejectSymlinkPath(statePath); err != nil {
		return persistedState{}, fmt.Errorf("runtime state path: %w", err)
	}
	file, err := os.Open(statePath)
	if err != nil {
		return persistedState{}, err
	}
	defer file.Close()
	b, err := io.ReadAll(io.LimitReader(file, maxRuntimeStateBytes+1))
	if err != nil {
		return persistedState{}, err
	}
	if int64(len(b)) > maxRuntimeStateBytes {
		return persistedState{}, fmt.Errorf("runtime %s state exceeds %d bytes", name, maxRuntimeStateBytes)
	}
	var state persistedState
	if err := json.Unmarshal(b, &state); err != nil {
		return persistedState{}, fmt.Errorf("decode runtime %s state: %w", name, err)
	}
	return state, nil
}

func (m *Manager) writeState(name string, state persistedState) error {
	return withFileLock(filepath.Join(m.root, ".manager.lock"), func() error {
		return m.writeStateUnlocked(name, state)
	})
}

func (m *Manager) writeStateUnlocked(name string, state persistedState) error {
	dir, err := m.runtimeDir(name)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(dir, "versions"), 0o750); err != nil {
		return err
	}
	data, err := json.MarshalIndent(state, "", "  ")
	if err != nil {
		return err
	}
	if int64(len(data)) > maxRuntimeStateBytes {
		return fmt.Errorf("runtime %s state exceeds %d bytes", name, maxRuntimeStateBytes)
	}
	tmp, err := os.CreateTemp(dir, ".state-*.json")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if err := tmp.Chmod(0o640); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, filepath.Join(dir, "state.json")); err != nil {
		return err
	}
	return syncDir(dir)
}

func (m *Manager) statusState(name string) (persistedState, error) {
	state, err := m.readState(name)
	if err == nil {
		return state, nil
	}
	// A missing state file is expected for a newly registered runtime and for
	// older installations that only persisted the in-memory status.  Every
	// other read failure (malformed JSON, a symlinked file, or an unsafe parent)
	// must remain visible to callers: silently treating it as an empty state
	// could make a control operation overwrite evidence of corruption or follow
	// an unexpected filesystem boundary.
	if !errors.Is(err, os.ErrNotExist) {
		return persistedState{}, err
	}
	status := m.status[name]
	if status.Name == "" {
		status = Status{Name: name, State: StateIdle, UpdatedAt: m.now()}
	}
	return persistedState{Status: status, Versions: make(map[string]Manifest)}, nil
}

// publishStatusLocked refreshes the lock-free control-plane view. Callers must
// hold m.mu while mutating m.status; the published slice contains value copies
// and is therefore safe for readers to use during a long provider operation.
func (m *Manager) publishStatusLocked() {
	view := make([]Status, 0, len(m.status))
	for _, status := range m.status {
		view = append(view, status)
	}
	sort.Slice(view, func(i, j int) bool { return view[i].Name < view[j].Name })
	m.statusView.Store(view)
}

func (m *Manager) setStatusLocked(name string, status Status) {
	if m.status == nil {
		m.status = make(map[string]Status)
	}
	m.status[name] = status
	m.publishStatusLocked()
}

func (m *Manager) deleteStatusLocked(name string) {
	delete(m.status, name)
	m.publishStatusLocked()
}

func (m *Manager) List() []Status {
	if m == nil {
		return nil
	}
	view, _ := m.statusView.Load().([]Status)
	out := make([]Status, len(view))
	copy(out, view)
	return out
}

func (m *Manager) Get(name string) (Status, bool) {
	if m == nil {
		return Status{}, false
	}
	for _, status := range m.List() {
		if status.Name == name {
			return status, true
		}
	}
	return Status{}, false
}

// Check verifies the currently active version without downloading or
// activating anything. It is deliberately side-effect free with respect to
// runtime pointers, which makes it safe to call while inference is busy.
// The state transition and journal entry make a check visible to the control
// plane and survive a restart.
// Check verifies the currently active version without downloading or
// activating anything. It is deliberately side-effect free with respect to
// runtime pointers, which makes it safe to call while inference is busy.
// The state transition and journal entry make a check visible to the control
// plane and survive a restart. Like Stage/Activate it releases m.mu while
// the provider's verify/health probes run.
// Check verifies the currently active version without downloading or
// activating anything. It is deliberately side-effect free with respect to
// runtime pointers, which makes it safe to call while inference is busy.
// The state transition and journal entry make a check visible to the control
// plane and survive a restart. Like Stage/Activate it releases m.mu while
// the provider's verify/health probes run. restoreStatus-style rollbacks
// expect m.mu to be held by the calling section.
func (m *Manager) Check(ctx context.Context, name string) (Status, error) {
	if m == nil {
		return Status{}, errors.New("runtime manager is nil")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	opLock := m.opLock(name)
	opLock.Lock()
	defer opLock.Unlock()

	withMu := func(fn func() error) error {
		m.mu.Lock()
		defer m.mu.Unlock()
		return fn()
	}

	var (
		manifest   Manifest
		provider   Provider
		versionDir string
		status     Status
		operation  Operation
	)
	// restoreStatus undoes the CHECKING status publication. It is assigned in
	// the preamble once the previous status is known and must be called with
	// m.mu held.
	var restoreStatus func()

	// Locked preamble: state reads, manifest resolution, CHECKING persist.
	preambleErr := withMu(func() error {
		if err := ctx.Err(); err != nil {
			return err
		}
		dir, err := m.runtimeDir(name)
		if err != nil {
			return err
		}
		state, err := m.statusState(name)
		if err != nil {
			return err
		}
		previousStatus, hadPreviousStatus := m.status[name]
		restored := false
		restoreStatus = func() {
			if restored {
				return
			}
			restored = true
			if hadPreviousStatus {
				m.setStatusLocked(name, previousStatus)
			} else {
				m.deleteStatusLocked(name)
			}
		}
		status = state.Status
		if status.Name == "" {
			status.Name = name
		}
		if status.Current == "" {
			return errors.New("runtime has no active version")
		}
		manifest, ok := state.Versions[status.Current]
		if !ok {
			// Versions are persisted by their logical version while the directory
			// uses safeVersion. Recover the manifest by comparing both forms.
			for version, candidate := range state.Versions {
				if safeVersion(version) == safeVersion(status.Current) {
					manifest, ok = candidate, true
					break
				}
			}
		}
		if !ok {
			status.State = StateDegraded
			status.LastError = "active runtime manifest is missing"
			status.LastCheck = m.now()
			status.UpdatedAt = m.now()
			m.setStatusLocked(name, status)
			missingErr := errors.New(status.LastError)
			if persistErr := m.persistStatus(name, status, nil); persistErr != nil {
				restoreStatus()
				return errors.Join(missingErr, persistErr)
			}
			return missingErr
		}
		provider, ok = m.providers[manifest.Kind]
		if !ok || isNilProvider(provider) {
			return fmt.Errorf("runtime %s: provider %q is not registered", name, manifest.Kind)
		}
		operation = Operation{ID: operationID(), Name: name, Action: "check", Version: manifest.Version, State: StateChecking, Timestamp: m.now()}
		status.State = StateChecking
		status.OperationID = operation.ID
		status.LastError = ""
		status.UpdatedAt = m.now()
		m.setStatusLocked(name, status)
		if err := m.appendOperation(operation); err != nil {
			restoreStatus()
			return err
		}
		if err := m.persistStatus(name, status, nil); err != nil {
			restoreStatus()
			return err
		}
		m.emitProgress(name, "checking", 0, "verifying active runtime", nil)
		versionDir = filepath.Join(dir, "versions", safeVersion(manifest.Version))
		return nil
	})
	if preambleErr != nil {
		return status, preambleErr
	}

	// Provider probes: run WITHOUT m.mu (the LMCache health probe starts a
	// real temporary server and can take minutes).
	checkErr := provider.Verify(ctx, manifest, versionDir)
	if checkErr == nil {
		checkErr = provider.Health(ctx, manifest, versionDir)
	}
	if checkErr == nil {
		// Providers are expected to honor cancellation, but a third-party
		// provider may return nil after the request deadline. Do not publish an
		// ACTIVE result for an operation that was canceled while it was running.
		checkErr = ctx.Err()
	}

	// Locked: final status. The durable ledger is left as-is — persistStatus
	// with nil versions re-reads the fresh on-disk state.
	err := withMu(func() error {
		status.LastCheck = m.now()
		status.UpdatedAt = m.now()
		if checkErr != nil {
			m.emitProgress(name, "error", 0, "runtime check failed", checkErr)
			status.State = StateDegraded
			status.LastError = checkErr.Error()
			operation.State = StateDegraded
			operation.Error = checkErr.Error()
		} else {
			m.emitProgress(name, "active", 1, "runtime check passed", nil)
			status.State = StateActive
			operation.State = StateActive
		}
		operation.Timestamp = m.now()
		m.setStatusLocked(name, status)
		if appendErr := m.appendOperation(operation); appendErr != nil {
			restoreStatus()
			return appendErr
		}
		if persistErr := m.persistStatus(name, status, nil); persistErr != nil {
			restoreStatus()
			return persistErr
		}
		return nil
	})
	if err != nil {
		return status, err
	}
	return status, checkErr
}

// Detail returns status, immutable manifests and recent journal operations.
func (m *Manager) Detail(name string) (Detail, bool, error) {
	if m == nil {
		return Detail{}, false, errors.New("runtime manager is nil")
	}
	var status Status
	var ok bool
	for _, candidate := range m.List() {
		if candidate.Name == name {
			status, ok = candidate, true
			break
		}
	}
	if !ok {
		return Detail{}, false, nil
	}
	state, err := m.readState(name)
	if errors.Is(err, os.ErrNotExist) {
		state = persistedState{Status: status, Versions: make(map[string]Manifest)}
	} else if err != nil {
		return Detail{}, false, err
	}
	operations, err := readOperations(filepath.Join(m.root, name, "operations.jsonl"))
	if err != nil {
		return Detail{}, false, err
	}
	return Detail{Status: status, Versions: state.Versions, Operations: operations}, true, nil
}

// VersionCatalog asks the configured provider for a source-aware version
// list, then enriches it with the manager's durable manifests and lifecycle
// pointers. Catalog discovery is read-only with respect to runtime material:
// it may query a package index or Git remote, but it never stages, activates,
// pulls, or changes the automatic-update candidate.
func (m *Manager) VersionCatalog(ctx context.Context, name string) (VersionCatalogResult, error) {
	if m == nil {
		return VersionCatalogResult{}, errors.New("runtime manager is nil")
	}
	if err := validateName(name); err != nil {
		return VersionCatalogResult{}, err
	}
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return VersionCatalogResult{}, err
	}

	m.mu.Lock()
	definition, configured := m.definitions[name]
	provider := Provider(nil)
	if configured {
		provider = m.providers[definition.Spec.Kind]
	}
	m.mu.Unlock()
	if !configured {
		return VersionCatalogResult{}, fmt.Errorf("runtime %s is not configured", name)
	}
	if isNilProvider(provider) {
		return VersionCatalogResult{}, fmt.Errorf("provider %q is not registered", definition.Spec.Kind)
	}

	result := VersionCatalogResult{
		SourceType: runtimeCatalogSourceType(definition.Spec),
	}
	if cataloger, ok := provider.(VersionCataloger); ok {
		result.Supported = true
		candidates, err := cataloger.ListVersions(ctx, definition.Spec, definition.Policy)
		if err != nil {
			return result, err
		}
		result.Versions = candidates
	}

	detail, ok, err := m.Detail(name)
	if err != nil {
		return VersionCatalogResult{}, err
	}
	if !ok {
		return VersionCatalogResult{}, fmt.Errorf("runtime %s is not registered", name)
	}
	result.Versions = mergeVersionCatalog(result.Versions, detail)
	return result, nil
}

// Register makes a configured runtime visible even before its first version
// is staged. It is idempotent and never replaces an existing persistent
// status, which is what allows a container restart or image upgrade to keep
// the current/previous pointers intact.
func (m *Manager) Register(name, kind string) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	if err := validateName(name); err != nil {
		return err
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.registerLocked(name, kind)
}

// registerLocked ensures a runtime has a status entry and a durable state
// file. Callers hold m.mu.
func (m *Manager) registerLocked(name, kind string) error {
	if _, err := m.runtimeDir(name); err != nil {
		return err
	}
	previousStatus, hadStatus := m.status[name]
	status := m.statusOrDefault(name, kind)
	if existing, ok := m.status[name]; ok {
		status = existing
		if status.Kind == "" {
			status.Kind = kind
		}
	} else {
		status.Kind = kind
		m.setStatusLocked(name, status)
	}
	state, err := m.statusState(name)
	if err != nil {
		if hadStatus {
			m.setStatusLocked(name, previousStatus)
		} else {
			m.deleteStatusLocked(name)
		}
		return err
	}
	state.Status = status
	if err := m.writeState(name, state); err != nil {
		if hadStatus {
			m.setStatusLocked(name, previousStatus)
		} else {
			m.deleteStatusLocked(name)
		}
		return err
	}
	return nil
}

// stageBundledRuntimeSource recognizes the compact layout used by the legacy
// Docker image, where llama.cpp is shipped as /app/llama-server rather than as
// a complete managed-runtime tree. The manager stores an immutable copy in the
// same layout as a source-built runtime so CurrentLaunchBinding can use it
// without retaining a path into the mutable image layer.
func stageBundledRuntimeSource(ctx context.Context, spec Spec, destination string) (Manifest, bool, error) {
	if !strings.EqualFold(strings.TrimSpace(spec.Kind), "llamacpp") {
		return Manifest{}, false, nil
	}
	source := strings.TrimSpace(spec.Source)
	if source == "" || destination == "" {
		return Manifest{}, false, nil
	}
	entrypoint := filepath.Join(source, "llama-server")
	info, err := os.Lstat(entrypoint)
	if errors.Is(err, os.ErrNotExist) {
		return Manifest{}, false, nil
	}
	if err != nil {
		return Manifest{}, true, err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return Manifest{}, true, errors.New("bundled llama.cpp entrypoint is not a regular file")
	}
	if info.Mode().Perm()&0o111 == 0 {
		return Manifest{}, true, errors.New("bundled llama.cpp entrypoint is not executable")
	}
	if err := rejectSymlinkPath(entrypoint); err != nil {
		return Manifest{}, true, fmt.Errorf("bundled llama.cpp entrypoint: %w", err)
	}
	if err := os.MkdirAll(filepath.Join(destination, "bin"), 0o750); err != nil {
		return Manifest{}, true, err
	}
	if err := os.MkdirAll(filepath.Join(destination, "build"), 0o750); err != nil {
		return Manifest{}, true, err
	}
	for _, name := range []string{"llama-server", "llama-cli", "llama-tts", "llama-bench", "ik-llama-server"} {
		candidate := filepath.Join(source, name)
		candidateInfo, statErr := os.Lstat(candidate)
		if errors.Is(statErr, os.ErrNotExist) {
			continue
		}
		if statErr != nil {
			return Manifest{}, true, statErr
		}
		// llama-server was validated above and is required. The remaining
		// binaries are optional convenience tools; ignore links or non-executable
		// entries rather than making a usable server asset unseedable.
		if candidateInfo.Mode()&os.ModeSymlink != 0 || !candidateInfo.Mode().IsRegular() || candidateInfo.Mode().Perm()&0o111 == 0 {
			continue
		}
		if err := copyBundledRuntimeFile(ctx, candidate, filepath.Join(destination, "bin", name), candidateInfo.Mode().Perm()); err != nil {
			return Manifest{}, true, fmt.Errorf("copy bundled llama.cpp binary %q: %w", name, err)
		}
	}
	metadata := cloneMetadata(spec.Metadata)
	if metadata == nil {
		metadata = make(map[string]string)
	}
	metadata["mode"] = RuntimeModeNative
	metadata["sourceType"] = "bundled"
	metadata["bundled"] = "true"
	if err := writeRuntimeMetadata(destination, metadata); err != nil {
		return Manifest{}, true, err
	}
	return Manifest{
		Name: spec.Name, Version: spec.Version, Kind: "llamacpp", Source: source,
		Ref: spec.Ref, Commit: spec.Commit, Checksum: spec.Checksum, Metadata: metadata,
		InstalledAt: time.Now().UTC(),
	}, true, nil
}

func copyBundledRuntimeFile(ctx context.Context, source, destination string, mode os.FileMode) error {
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	in, err := os.Open(source)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(destination, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, mode)
	if err != nil {
		return err
	}
	_, copyErr := io.Copy(out, in)
	syncErr := out.Sync()
	closeErr := out.Close()
	if err := ctx.Err(); err != nil {
		return err
	}
	return errors.Join(copyErr, syncErr, closeErr)
}

// SeedIfMissing copies an image-provided bundled runtime into the persistent
// runtime root exactly once. The persistent current pointer is authoritative:
// a valid current runtime is returned without touching the source tree, while
// a dangling or operator-owned pointer is rejected rather than overwritten.
// This is intentionally separate from Stage so an image upgrade cannot trigger
// a download/build or replace a runtime that an operator already activated.
func (m *Manager) SeedIfMissing(ctx context.Context, spec Spec) (Manifest, bool, error) {
	if m == nil {
		return Manifest{}, false, errors.New("runtime manager is nil")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return Manifest{}, false, err
	}
	if err := validateName(spec.Name); err != nil {
		return Manifest{}, false, err
	}
	if strings.TrimSpace(spec.Kind) == "" {
		return Manifest{}, false, errors.New("bundled runtime kind is required")
	}
	if err := validateName(spec.Version); err != nil {
		return Manifest{}, false, fmt.Errorf("bundled runtime version: %w", err)
	}
	if strings.TrimSpace(spec.Version) == "" {
		return Manifest{}, false, errors.New("bundled runtime version is required")
	}
	if !strings.EqualFold(strings.TrimSpace(spec.SourceType), "bundled") {
		return Manifest{}, false, errors.New("runtime seed requires source type bundled")
	}
	source := strings.TrimSpace(spec.Source)
	if source == "" || strings.IndexByte(source, 0) >= 0 {
		return Manifest{}, false, errors.New("bundled runtime source path is required")
	}
	if !filepath.IsAbs(source) {
		return Manifest{}, false, errors.New("bundled runtime source path must be absolute")
	}

	m.mu.Lock()
	defer m.mu.Unlock()
	dir, err := m.runtimeDir(spec.Name)
	if err != nil {
		return Manifest{}, false, err
	}
	// Never copy a source tree into itself (or into a child of itself). Apart
	// from being unsafe, filepath.Walk would otherwise observe its own output.
	sourceAbs, err := filepath.Abs(source)
	if err != nil {
		return Manifest{}, false, err
	}
	runtimeAbs, err := filepath.Abs(dir)
	if err != nil {
		return Manifest{}, false, err
	}
	if pathContains(sourceAbs, runtimeAbs) || pathContains(runtimeAbs, sourceAbs) {
		return Manifest{}, false, errors.New("bundled runtime source overlaps persistent runtime root")
	}

	currentPath := filepath.Join(dir, "current")
	if info, statErr := os.Lstat(currentPath); statErr == nil {
		if info.Mode()&os.ModeSymlink == 0 {
			return Manifest{}, false, errors.New("runtime current pointer is not a symlink")
		}
		current, linkErr := readLink(currentPath)
		if linkErr != nil {
			return Manifest{}, false, fmt.Errorf("runtime current pointer: %w", linkErr)
		}
		if err := validVersionDir(dir, current); err != nil {
			return Manifest{}, false, fmt.Errorf("runtime current pointer: %w", err)
		}
		manifest, manifestErr := readManifest(filepath.Join(dir, "versions", current, "manifest.json"))
		if manifestErr != nil {
			return Manifest{}, false, fmt.Errorf("read active bundled runtime manifest: %w", manifestErr)
		}
		if err := manifest.Validate(); err != nil {
			return Manifest{}, false, fmt.Errorf("active bundled runtime manifest: %w", err)
		}
		return manifest, false, nil
	} else if !errors.Is(statErr, os.ErrNotExist) {
		return Manifest{}, false, statErr
	}

	if err := rejectSymlinkPath(sourceAbs); err != nil {
		return Manifest{}, false, fmt.Errorf("bundled runtime source: %w", err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "versions"), 0o750); err != nil {
		return Manifest{}, false, err
	}
	stageDir, err := os.MkdirTemp(filepath.Join(dir, "versions"), ".staging-")
	if err != nil {
		return Manifest{}, false, err
	}
	defer os.RemoveAll(stageDir)

	operation := Operation{ID: operationID(), Name: spec.Name, Action: "seed", Version: spec.Version, State: StateStaging, Timestamp: m.now()}
	status := m.statusOrDefault(spec.Name, spec.Kind)
	previousStatus, hadPreviousStatus := m.status[spec.Name]
	restoreStatus := func() {
		if hadPreviousStatus {
			m.setStatusLocked(spec.Name, previousStatus)
		} else {
			m.deleteStatusLocked(spec.Name)
		}
	}
	status.OperationID = operation.ID
	status.State = StateStaging
	status.LastError = ""
	status.UpdatedAt = m.now()
	m.setStatusLocked(spec.Name, status)
	if err := m.appendOperation(operation); err != nil {
		restoreStatus()
		return Manifest{}, false, fmt.Errorf("record bundled runtime seed transition: %w", err)
	}
	if err := m.persistStatus(spec.Name, status, nil); err != nil {
		if hadPreviousStatus {
			restoreStatus()
		} else {
			failed := status
			failed.State = StateDegraded
			failed.LastError = err.Error()
			failed.UpdatedAt = m.now()
			m.setStatusLocked(spec.Name, failed)
		}
		return Manifest{}, false, fmt.Errorf("persist bundled runtime seed transition: %w", err)
	}
	m.emitProgress(spec.Name, "staging", 0, "seeding bundled runtime", nil)
	var finalDir string
	committedDir := false
	pointerCommitted := false
	seedFailure := func(cause error) (Manifest, bool, error) {
		if cause == nil {
			cause = errors.New("bundled runtime seed failed")
		}
		// A seed never replaces an existing current pointer. If a failure happens
		// after the candidate was renamed or linked, remove only the paths this
		// invocation created so a retry can safely start from the same image
		// asset. Do not remove a pre-existing version on a collision error.
		if pointerCommitted {
			if err := restorePointer(dir, "current", ""); err != nil {
				cause = errors.Join(cause, fmt.Errorf("remove seeded current pointer: %w", err))
			}
			pointerCommitted = false
		}
		if committedDir && finalDir != "" {
			if err := os.RemoveAll(finalDir); err != nil {
				cause = errors.Join(cause, fmt.Errorf("remove seeded candidate: %w", err))
			}
			if err := syncDir(filepath.Join(dir, "versions")); err != nil {
				cause = errors.Join(cause, fmt.Errorf("sync seeded versions: %w", err))
			}
			committedDir = false
		}
		m.emitProgress(spec.Name, "error", 0, "bundled runtime seed failed", cause)
		operation.State = StateDegraded
		operation.Error = cause.Error()
		operation.Timestamp = m.now()
		if err := m.appendOperation(operation); err != nil {
			cause = errors.Join(cause, fmt.Errorf("record bundled runtime seed failure: %w", err))
		}
		status.State = StateDegraded
		status.LastError = cause.Error()
		status.UpdatedAt = m.now()
		m.setStatusLocked(spec.Name, status)
		if err := m.persistStatus(spec.Name, status, nil); err != nil {
			cause = errors.Join(cause, fmt.Errorf("persist bundled runtime seed failure: %w", err))
		}
		return Manifest{}, false, cause
	}

	seedSpec := Spec{
		Name:       spec.Name,
		Kind:       spec.Kind,
		Version:    spec.Version,
		Source:     sourceAbs,
		SourceType: "bundled",
		Ref:        spec.Ref,
		Commit:     spec.Commit,
		Checksum:   spec.Checksum,
		Metadata:   cloneMetadata(spec.Metadata),
	}
	manifest, handled, stageErr := stageBundledRuntimeSource(ctx, seedSpec, stageDir)
	if !handled {
		manifest, stageErr = (CopyProvider{}).Stage(ctx, seedSpec, stageDir)
	}
	err = stageErr
	if err == nil {
		err = ctx.Err()
	}
	if err == nil {
		manifest.InstalledAt = m.now()
		if manifest.Name == "" {
			manifest.Name = spec.Name
		}
		if manifest.Version == "" {
			manifest.Version = spec.Version
		}
		if manifest.Kind == "" {
			manifest.Kind = spec.Kind
		}
		if manifest.Source == "" {
			manifest.Source = sourceAbs
		}
		err = validateManifestIdentity(manifest, Spec{Name: spec.Name, Kind: spec.Kind, Version: spec.Version})
		if err == nil {
			err = manifest.Validate()
		}
	}
	// Publish VERIFYING before invoking provider hooks. A provider may perform
	// a real health probe, and the journal must expose that phase even when the
	// probe fails or ignores cancellation.
	if err == nil {
		operation.State = StateVerifying
		operation.Timestamp = m.now()
		if appendErr := m.appendOperation(operation); appendErr != nil {
			return seedFailure(fmt.Errorf("record bundled runtime verifying transition: %w", appendErr))
		}
		status.State = StateVerifying
		status.UpdatedAt = m.now()
		m.setStatusLocked(spec.Name, status)
		if persistErr := m.persistStatus(spec.Name, status, nil); persistErr != nil {
			return seedFailure(fmt.Errorf("persist bundled runtime verifying transition: %w", persistErr))
		}
		m.emitProgress(spec.Name, "verifying", 0.8, "verifying bundled runtime", nil)
	}
	provider := m.providers[spec.Kind]
	if isNilProvider(provider) {
		provider = CopyProvider{}
	}
	if err == nil {
		err = provider.Verify(ctx, manifest, stageDir)
	}
	if err == nil {
		err = provider.Health(ctx, manifest, stageDir)
	}
	if err == nil {
		err = ctx.Err()
	}
	if err != nil {
		return seedFailure(err)
	}

	finalDir = filepath.Join(dir, "versions", safeVersion(manifest.Version))
	if _, statErr := os.Stat(finalDir); statErr == nil {
		return seedFailure(fmt.Errorf("runtime version %s already exists without current pointer", manifest.Version))
	} else if !errors.Is(statErr, os.ErrNotExist) {
		return seedFailure(statErr)
	}
	if err := writeManifest(stageDir, manifest); err != nil {
		return seedFailure(err)
	}
	if err := ctx.Err(); err != nil {
		return seedFailure(err)
	}
	if err := os.Rename(stageDir, finalDir); err != nil {
		return seedFailure(fmt.Errorf("commit bundled runtime: %w", err))
	}
	committedDir = true
	if err := syncDir(filepath.Join(dir, "versions")); err != nil {
		return seedFailure(err)
	}
	if err := ctx.Err(); err != nil {
		return seedFailure(err)
	}
	if err := atomicLink(dir, "current", safeVersion(manifest.Version)); err != nil {
		return seedFailure(err)
	}
	pointerCommitted = true
	if err := ctx.Err(); err != nil {
		return seedFailure(err)
	}

	state, stateErr := m.statusState(spec.Name)
	if stateErr != nil {
		return seedFailure(stateErr)
	}
	if state.Versions == nil {
		state.Versions = make(map[string]Manifest)
	}
	state.Versions[manifest.Version] = manifest
	status.Current = manifest.Version
	status.Source = manifest.Source
	status.Kind = manifest.Kind
	status.Staged = ""
	status.State = StateActive
	status.LastUpdate = m.now()
	status.UpdatedAt = m.now()
	state.Status = status
	m.setStatusLocked(spec.Name, status)
	if err := m.writeState(spec.Name, state); err != nil {
		return seedFailure(err)
	}
	// The state file and current pointer are durable before ACTIVE is journaled;
	// this ordering lets startup recovery treat the pointer as authoritative if
	// the process is terminated between these two writes.
	operation.State = StateActive
	operation.Timestamp = m.now()
	if err := m.appendOperation(operation); err != nil {
		return seedFailure(fmt.Errorf("record active bundled runtime transition: %w", err))
	}
	pointerCommitted = false
	committedDir = false
	m.emitProgress(spec.Name, "active", 1, "bundled runtime active", nil)
	return manifest, true, nil
}

func pathContains(base, target string) bool {
	rel, err := filepath.Rel(base, target)
	return err == nil && (rel == "." || (rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))))
}

// opLockForStage is documented on opLock: Stage serializes per runtime and
// releases m.mu during the provider's download/build and verify sections.
func (m *Manager) Stage(ctx context.Context, spec Spec) (Manifest, error) {
	if m == nil {
		return Manifest{}, errors.New("runtime manager is nil")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	opLock := m.opLock(spec.Name)
	opLock.Lock()
	defer opLock.Unlock()

	withMu := func(fn func() error) error {
		m.mu.Lock()
		defer m.mu.Unlock()
		return fn()
	}

	var (
		dir               string
		stageDir          string
		providerRef       Provider
		previousStatus    Status
		hadPreviousStatus bool
		status            Status
		operation         Operation
		stagedManifest    Manifest
		idempotent        bool
	)

	// Locked preamble: validation, the idempotence fast path, the busy gate,
	// staging-directory creation, and the durable STAGING/DOWNLOADING/BUILDING
	// transitions. Failures here have already restored the previous status.
	err := withMu(func() error {
		if err := ctx.Err(); err != nil {
			return err
		}
		var innerErr error
		dir, innerErr = m.runtimeDir(spec.Name)
		if innerErr != nil {
			return innerErr
		}
		provider, ok := m.providers[spec.Kind]
		if !ok || isNilProvider(provider) {
			return fmt.Errorf("runtime %s: provider %q is not registered", spec.Name, spec.Kind)
		}
		providerRef = provider
		if spec.Version == "" {
			return errors.New("runtime version is required before staging")
		}
		if err := validateVersion(spec.Version); err != nil {
			return err
		}
		if err := validateRuntimeSpecReferences(spec, spec.Kind); err != nil {
			return err
		}
		// Staging is idempotent for a version that is already installed: the
		// version directory is immutable and the build is reproducible from the
		// source, so return the recorded manifest instead of re-downloading,
		// rebuilding, and failing on the commit guard below. The caller (the
		// automatic update loop or an explicit API call) decides whether to
		// activate it. A directory that exists without a ledger entry is an
		// inconsistent state, so it falls through and the post-build commit
		// guard reports it through the normal failure-recording path.
		if _, err := os.Stat(filepath.Join(dir, "versions", safeVersion(spec.Version))); err == nil {
			if state, stateErr := m.statusState(spec.Name); stateErr == nil {
				if existing, ok := state.Versions[spec.Version]; ok {
					stagedManifest = existing
					idempotent = true
					return nil
				}
			}
		}
		if !m.idleNowFor(spec.Name) && !m.buildWhileBusyAllowed() {
			busy := m.statusOrDefault(spec.Name, spec.Kind)
			busy.State = StateWaitingForIdle
			busy.LastError = "runtime is busy; staging deferred"
			busy.UpdatedAt = m.now()
			m.setStatusLocked(spec.Name, busy)
			busyErr := fmt.Errorf("%w: runtime %s is busy", ErrRuntimeBusy, spec.Name)
			if persistErr := m.persistStatus(spec.Name, busy, nil); persistErr != nil {
				return errors.Join(busyErr, persistErr)
			}
			return busyErr
		}
		if err := os.MkdirAll(filepath.Join(dir, "versions"), 0o750); err != nil {
			return err
		}
		var mkErr error
		stageDir, mkErr = os.MkdirTemp(filepath.Join(dir, "versions"), ".staging-")
		if mkErr != nil {
			return mkErr
		}

		// Keep the in-memory status transactional across the durable transition
		// preamble. A failed journal/state write must not make a stage operation look
		// active in the control plane while the on-disk state still points at the
		// previous status.
		if m.status == nil {
			m.status = make(map[string]Status)
		}
		previousStatus, hadPreviousStatus = m.status[spec.Name]
		restoreStatus := func() {
			if hadPreviousStatus {
				m.setStatusLocked(spec.Name, previousStatus)
			} else {
				m.deleteStatusLocked(spec.Name)
			}
		}
		persistTransition := func(next Operation, nextStatus Status) error {
			if err := m.appendOperation(next); err != nil {
				restoreStatus()
				return err
			}
			m.setStatusLocked(spec.Name, nextStatus)
			if err := m.persistStatus(spec.Name, nextStatus, nil); err != nil {
				if hadPreviousStatus {
					restoreStatus()
				} else {
					// There is no prior durable status to restore for a newly seen
					// runtime. Keep an in-memory DEGRADED marker so callers can
					// diagnose the state-file failure even when the failed write was
					// caused by a symlink, permissions, or another filesystem fault.
					failed := nextStatus
					failed.State = StateDegraded
					failed.LastError = err.Error()
					failed.UpdatedAt = m.now()
					m.setStatusLocked(spec.Name, failed)
				}
				return err
			}
			return nil
		}
		status = m.statusOrDefault(spec.Name, spec.Kind)
		status.Mode = normalizeRuntimeMode(spec.Mode)
		operation = Operation{ID: operationID(), Name: spec.Name, Action: "stage", Version: spec.Version, State: StateStaging, Timestamp: m.now()}
		status.OperationID = operation.ID
		status.State = StateStaging
		status.LastError = ""
		status.UpdatedAt = m.now()
		if err := persistTransition(operation, status); err != nil {
			return fmt.Errorf("persist runtime staging transition: %w", err)
		}
		m.emitProgress(spec.Name, "staging", 0, "staging runtime", nil)
		// Providers may combine download and build internally, but keep both phases
		// explicit in the journal so operators can distinguish a network/source
		// interruption from a compiler or environment failure after restart.
		operation.State = StateDownloading
		operation.Timestamp = m.now()
		status.State = StateDownloading
		status.UpdatedAt = m.now()
		if err := persistTransition(operation, status); err != nil {
			return fmt.Errorf("persist runtime downloading transition: %w", err)
		}
		m.emitProgress(spec.Name, "downloading", 0.05, "downloading runtime source", nil)
		operation.State = StateBuilding
		operation.Timestamp = m.now()
		status.State = StateBuilding
		status.UpdatedAt = m.now()
		if err := persistTransition(operation, status); err != nil {
			return fmt.Errorf("persist runtime building transition: %w", err)
		}
		m.emitProgress(spec.Name, "building", 0.1, "building runtime", nil)
		return nil
	})
	if stageDir != "" {
		defer os.RemoveAll(stageDir)
	}
	if idempotent {
		return stagedManifest, nil
	}
	if err != nil {
		return Manifest{}, err
	}

	// stageFailure records the durable DEGRADED outcome. It acquires m.mu
	// itself and must only be called from sections that do NOT hold it.
	var finalDir string
	candidateCommitted := false
	stageFailure := func(cause error) (Manifest, error) {
		if cause == nil {
			cause = errors.New("runtime staging failed")
		}
		if candidateCommitted && finalDir != "" {
			cleanupErr := os.RemoveAll(finalDir)
			syncErr := syncDir(filepath.Join(dir, "versions"))
			if cleanupErr != nil || syncErr != nil {
				cause = errors.Join(cause, cleanupErr, syncErr)
			}
			candidateCommitted = false
		}
		m.emitProgress(spec.Name, "error", 0, "runtime staging failed", cause)
		operation.State = StateDegraded
		operation.Error = cause.Error()
		operation.Timestamp = m.now()
		status.State = StateDegraded
		status.LastError = cause.Error()
		status.UpdatedAt = m.now()
		var persistErrs []error
		if err := withMu(func() error {
			m.setStatusLocked(spec.Name, status)
			if err := m.appendOperation(operation); err != nil {
				return fmt.Errorf("record runtime staging failure: %w", err)
			}
			if err := m.persistStatus(spec.Name, status, nil); err != nil {
				if hadPreviousStatus {
					m.setStatusLocked(spec.Name, previousStatus)
				}
				return fmt.Errorf("persist runtime staging failure: %w", err)
			}
			return nil
		}); err != nil {
			persistErrs = append(persistErrs, err)
		}
		return Manifest{}, errors.Join(append([]error{cause}, persistErrs...)...)
	}

	stageCtx := withRuntimeProgress(ctx, func(phase string, progress float64, message string) {
		m.emitProgress(spec.Name, phase, progress, message, nil)
	})
	stageCtx = withRuntimeProgressBytes(stageCtx, func(phase string, progress float64, completed, total int64, message string) {
		m.emitProgressBytes(spec.Name, phase, progress, completed, total, message, nil)
	})
	stageCtx = withRuntimeCommandOutputState(stageCtx)
	stageCtx = withRuntimeLog(stageCtx, func(stream string, output []byte) {
		m.emitRuntimeLog(spec.Name, operation.ID, stream, output)
	})

	// Provider download/build: runs WITHOUT m.mu so other runtimes and the
	// control plane proceed while this build runs.
	manifest, err := providerRef.Stage(stageCtx, spec, stageDir)
	if err != nil {
		return stageFailure(err)
	}

	// Locked: manifest finalization and the durable VERIFYING transition.
	err = withMu(func() error {
		if manifest.Name == "" {
			manifest.Name = spec.Name
		}
		if manifest.Version == "" {
			manifest.Version = spec.Version
		}
		if manifest.Kind == "" {
			manifest.Kind = spec.Kind
		}
		if manifest.Source == "" {
			manifest.Source = spec.Source
		}
		if manifest.Ref == "" {
			manifest.Ref = spec.Ref
		}
		if manifest.Commit == "" {
			manifest.Commit = spec.Commit
		}
		if manifest.Checksum == "" {
			manifest.Checksum = spec.Checksum
		}
		if manifest.InstalledAt.IsZero() {
			manifest.InstalledAt = m.now()
		}
		if err := validateManifestIdentity(manifest, spec); err != nil {
			return err
		}
		if err := manifest.Validate(); err != nil {
			return err
		}
		if err := writeManifest(stageDir, manifest); err != nil {
			return err
		}
		status.State = StateVerifying
		operation.State = StateVerifying
		operation.Timestamp = m.now()
		if err := m.appendOperation(operation); err != nil {
			return fmt.Errorf("record runtime verifying transition: %w", err)
		}
		status.UpdatedAt = m.now()
		m.setStatusLocked(spec.Name, status)
		m.emitProgress(spec.Name, "verifying", 0.8, "verifying staged runtime", nil)
		return nil
	})
	if err != nil {
		return stageFailure(err)
	}

	// Verification probe: runs WITHOUT m.mu (the LMCache probe starts a real
	// temporary server and can take minutes).
	if err := providerRef.Verify(ctx, manifest, stageDir); err != nil {
		return stageFailure(fmt.Errorf("verify staged runtime: %w", err))
	}
	if err := ctx.Err(); err != nil {
		return stageFailure(err)
	}

	// Locked: the commit — rename into versions/, ledger update, STAGED state.
	// The ledger is re-read fresh: a concurrent Pin or removal may have
	// committed while the build ran, and writing the stale preamble snapshot
	// would clobber it.
	err = withMu(func() error {
		finalDir = filepath.Join(dir, "versions", safeVersion(manifest.Version))
		// Once the staging directory is renamed into versions it becomes a
		// manager-owned candidate. Any subsequent durability/state failure must
		// remove that candidate again; otherwise a retry can see an orphaned
		// version directory while the journal still describes an unfinished build.
		if _, err := os.Stat(finalDir); err == nil {
			return fmt.Errorf("runtime version %s is already installed", manifest.Version)
		} else if !errors.Is(err, os.ErrNotExist) {
			return err
		}
		if err := os.Rename(stageDir, finalDir); err != nil {
			return fmt.Errorf("commit staged runtime: %w", err)
		}
		candidateCommitted = true
		// uv-generated console scripts embed the absolute interpreter path used
		// while creating the virtualenv. Stage runs inside a temporary directory,
		// so leaving that shebang untouched would make the activated command
		// fail with ENOENT even though the virtualenv itself is valid. Rewrite
		// only managed venv entrypoint shebangs after the candidate has its
		// durable version path; any failure is handled by the same candidate
		// compensation path below. The lmcache derived runtime needs the same
		// repair because its server is launched through the venv console script.
		if manifest.Kind == "vllm" || manifest.Kind == "lmcache" {
			if err := rewriteVenvEntrypointShebangs(finalDir, stageDir, finalDir); err != nil {
				return fmt.Errorf("rewrite venv entrypoint shebangs: %w", err)
			}
		}
		if err := syncDir(filepath.Join(dir, "versions")); err != nil {
			return err
		}
		if cancelErr := ctx.Err(); cancelErr != nil {
			// The provider result has already been renamed into the immutable
			// versions directory, but no state entry points at it yet. Remove that
			// candidate before returning so cancellation cannot leave an apparently
			// staged version that the caller did not ask to install.
			return cancelErr
		}
		state, stateErr := m.statusState(spec.Name)
		if stateErr != nil {
			return stateErr
		}
		if state.Versions == nil {
			state.Versions = make(map[string]Manifest)
		}
		state.Versions[manifest.Version] = manifest
		status.State = StateStaged
		operation.State = StateStaged
		operation.Timestamp = m.now()
		if err := m.appendOperation(operation); err != nil {
			return fmt.Errorf("record staged runtime transition: %w", err)
		}
		status.Staged = manifest.Version
		status.Kind = manifest.Kind
		status.Source = manifest.Source
		status.UpdatedAt = m.now()
		state.Status = status
		m.setStatusLocked(spec.Name, status)
		if err := m.writeState(spec.Name, state); err != nil {
			return err
		}
		candidateCommitted = false
		return nil
	})
	if err != nil {
		return stageFailure(err)
	}
	m.emitProgress(spec.Name, "staged", 1, "runtime staged", nil)
	return manifest, nil
}

const maxRuntimeEntrypointScriptBytes = 1 << 20

// rewriteVenvEntrypointShebangs repairs absolute uv/python console-script
// interpreters after a staged runtime is renamed from its temporary directory
// into the immutable version directory. Only regular files directly under
// .venv/bin are inspected; symlinked interpreters and non-script files are
// left untouched. The replacement is intentionally limited to the old
// manager-owned prefix, so arbitrary script content or an operator-provided
// external interpreter path cannot be rewritten accidentally.
func rewriteVenvEntrypointShebangs(directory, oldPrefix, newPrefix string) error {
	if strings.TrimSpace(directory) == "" || strings.TrimSpace(oldPrefix) == "" || strings.TrimSpace(newPrefix) == "" {
		return errors.New("venv entrypoint rewrite paths are required")
	}
	oldPrefix = filepath.Clean(oldPrefix)
	newPrefix = filepath.Clean(newPrefix)
	binDir := filepath.Join(directory, ".venv", "bin")
	if err := rejectSymlinkPath(binDir); err != nil {
		return err
	}
	entries, err := os.ReadDir(binDir)
	if errors.Is(err, os.ErrNotExist) {
		// Custom providers may label a manifest vLLM while managing their own
		// launch surface. The provider's Verify method remains authoritative;
		// there is simply nothing for this compatibility repair to rewrite.
		return nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		path := filepath.Join(binDir, entry.Name())
		info, statErr := os.Lstat(path)
		if statErr != nil {
			return statErr
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
			continue
		}
		file, openErr := os.Open(path)
		if openErr != nil {
			return openErr
		}
		content, readErr := io.ReadAll(io.LimitReader(file, maxRuntimeEntrypointScriptBytes+1))
		closeErr := file.Close()
		if readErr != nil {
			return readErr
		}
		if closeErr != nil {
			return closeErr
		}
		if len(content) > maxRuntimeEntrypointScriptBytes {
			continue
		}
		lineEnd := strings.IndexByte(string(content), '\n')
		if lineEnd < 0 {
			lineEnd = len(content)
		}
		shebang := string(content[:lineEnd])
		if !strings.HasPrefix(shebang, "#!") || !strings.Contains(shebang, oldPrefix) {
			continue
		}
		rewritten := strings.Replace(shebang, oldPrefix, newPrefix, 1)
		if rewritten == shebang {
			continue
		}
		updated := make([]byte, 0, len(content)+len(newPrefix)-len(oldPrefix))
		updated = append(updated, rewritten...)
		updated = append(updated, content[lineEnd:]...)
		if err := rewriteRuntimeFile(path, updated, info.Mode().Perm()); err != nil {
			return fmt.Errorf("rewrite %s: %w", entry.Name(), err)
		}
	}
	return syncDir(binDir)
}

func rewriteRuntimeFile(path string, content []byte, mode os.FileMode) error {
	directory := filepath.Dir(path)
	tmp, err := os.CreateTemp(directory, ".rewrite-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		return err
	}
	return syncDir(directory)
}

func safeVersion(version string) string {
	version = strings.TrimSpace(version)
	version = strings.ReplaceAll(version, "/", "_")
	version = strings.ReplaceAll(version, "\\", "_")
	if version == "" || version == "." || version == ".." {
		return "unknown"
	}
	return version
}

// Activate switches the serving pointer to a staged version. It serializes
// per runtime via the op lock and releases m.mu during the provider's
// verify/health probes and the switch hooks: those can run for minutes (the
// LMCache health probe starts a real temporary server; the switch hooks drain
// and restart models), and holding m.mu across them would block the control
// plane and every other runtime. The H9 apply/activation deadlock pair is
// dissolved by construction here: switchAfter no longer waits for a config
// apply while holding m.mu.
func (m *Manager) Activate(ctx context.Context, name, version string) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	opLock := m.opLock(name)
	opLock.Lock()
	defer opLock.Unlock()

	withMu := func(fn func() error) error {
		m.mu.Lock()
		defer m.mu.Unlock()
		return fn()
	}

	var (
		dir                   string
		manifest              Manifest
		providerRef           Provider
		versionDir            string
		oldCurrent            string
		oldPrevious           string
		switchBefore          RuntimeSwitchHook
		switchAfter           RuntimeSwitchHook
		pointerMayHaveChanged bool
	)
	var status Status
	var operation Operation

	// activateFailure records the durable rollback outcome under m.mu and,
	// once the pointer may have moved, compensates the process launch
	// configuration. It must only be called from sections that do NOT hold
	// m.mu; the preamble's own failures call m.activationFailure directly
	// while still holding it (no pointer can have moved yet there).
	activateFailure := func(cause error) error {
		var failure error
		if err := withMu(func() error {
			failure = m.activationFailure(name, oldCurrent, oldPrevious, cause)
			return nil
		}); err != nil {
			failure = errors.Join(cause, err)
		}
		if !pointerMayHaveChanged || switchAfter == nil {
			return failure
		}
		// The original request may have been canceled after the pointer exchange;
		// compensation still needs to restore the process launch configuration.
		compensationCtx := context.WithoutCancel(ctx)
		if hookErr := switchAfter(compensationCtx, name, safeVersion(version), oldCurrent); hookErr != nil {
			return errors.Join(failure, fmt.Errorf("restore runtime process configuration: %w", hookErr))
		}
		return failure
	}

	// Locked preamble: validation, the busy gate, state reads, the operation
	// journal and the durable ACTIVATING transition.
	preambleErr := withMu(func() error {
		if err := ctx.Err(); err != nil {
			return err
		}
		if err := validateVersion(version); err != nil {
			return err
		}
		if !m.idleNowFor(name) {
			busy := m.statusOrDefault(name, "")
			busy.State = StateWaitingForIdle
			busy.UpdatedAt = m.now()
			m.setStatusLocked(name, busy)
			busyErr := fmt.Errorf("%w: runtime %s is busy", ErrRuntimeBusy, name)
			if err := m.persistStatus(name, busy, nil); err != nil {
				return errors.Join(busyErr, fmt.Errorf("persist waiting-for-idle runtime status: %w", err))
			}
			return busyErr
		}
		var err error
		dir, err = m.runtimeDir(name)
		if err != nil {
			return err
		}
		state, err := m.statusState(name)
		if err != nil {
			return err
		}
		ledgerManifest, ok := state.Versions[version]
		if !ok {
			return fmt.Errorf("runtime %s version %s is not staged", name, version)
		}
		manifest = ledgerManifest
		provider, ok := m.providers[manifest.Kind]
		if !ok || isNilProvider(provider) {
			return fmt.Errorf("runtime %s: provider %q is not registered", name, manifest.Kind)
		}
		providerRef = provider
		versionDir = filepath.Join(dir, "versions", safeVersion(version))
		if err := validVersionDir(dir, version); err != nil {
			return fmt.Errorf("runtime %s version %s directory is missing", name, version)
		}
		oldCurrent, err = readLink(filepath.Join(dir, "current"))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		oldPrevious, err = readLink(filepath.Join(dir, "previous"))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		switchBefore, switchAfter = m.activationHooks()
		status = state.Status
		status.Mode = manifestMode(manifest)
		if m.status == nil {
			m.status = make(map[string]Status)
		}
		previousStatus, hadPreviousStatus := m.status[name]
		restoreStatus := func() {
			if hadPreviousStatus {
				m.setStatusLocked(name, previousStatus)
			} else {
				m.deleteStatusLocked(name)
			}
		}
		operation = Operation{ID: operationID(), Name: name, Action: "activate", Version: version, State: StateActivating, Timestamp: m.now()}
		status.OperationID = operation.ID
		if err := m.appendOperation(operation); err != nil {
			restoreStatus()
			return fmt.Errorf("record runtime activation transition: %w", err)
		}
		status.State = StateActivating
		status.UpdatedAt = m.now()
		m.setStatusLocked(name, status)
		m.emitProgress(name, "activating", 0, "activating runtime", nil)
		state.Status = status
		if err := m.writeState(name, state); err != nil {
			return m.activationFailure(name, oldCurrent, oldPrevious, err)
		}
		return nil
	})
	if preambleErr != nil {
		return preambleErr
	}

	// Verification probe: runs WITHOUT m.mu.
	if err := providerRef.Verify(ctx, manifest, versionDir); err != nil {
		m.emitProgress(name, "rollback", 0, "runtime activation verification failed", err)
		operation.State = StateRollback
		operation.Error = err.Error()
		operation.Timestamp = m.now()
		if appendErr := withMu(func() error { return m.appendOperation(operation) }); appendErr != nil {
			err = errors.Join(err, fmt.Errorf("record runtime activation rollback: %w", appendErr))
		}
		return activateFailure(err)
	}
	if err := ctx.Err(); err != nil {
		operation.State = StateRollback
		operation.Error = err.Error()
		operation.Timestamp = m.now()
		if appendErr := withMu(func() error { return m.appendOperation(operation) }); appendErr != nil {
			err = errors.Join(err, fmt.Errorf("record runtime activation cancellation: %w", appendErr))
		}
		return activateFailure(err)
	}

	if err := withMu(func() error {
		status.State = StateHealthCheck
		status.UpdatedAt = m.now()
		m.setStatusLocked(name, status)
		return nil
	}); err != nil {
		return err
	}
	m.emitProgress(name, "health_check", 0.7, "checking runtime health", nil)

	// Health probe: runs WITHOUT m.mu.
	if err := providerRef.Health(ctx, manifest, versionDir); err != nil {
		m.emitProgress(name, "rollback", 0, "runtime health check failed", err)
		operation.State = StateRollback
		operation.Error = err.Error()
		operation.Timestamp = m.now()
		if appendErr := withMu(func() error { return m.appendOperation(operation) }); appendErr != nil {
			err = errors.Join(err, fmt.Errorf("record runtime health rollback: %w", appendErr))
		}
		return activateFailure(err)
	}
	if err := ctx.Err(); err != nil {
		operation.State = StateRollback
		operation.Error = err.Error()
		operation.Timestamp = m.now()
		if appendErr := withMu(func() error { return m.appendOperation(operation) }); appendErr != nil {
			err = errors.Join(err, fmt.Errorf("record runtime health cancellation: %w", appendErr))
		}
		return activateFailure(err)
	}

	// switchBefore prepares the process topology; it fences and drains models
	// and can wait a long time, so it runs WITHOUT m.mu.
	if switchBefore != nil && oldCurrent != safeVersion(version) {
		if err := switchBefore(ctx, name, oldCurrent, safeVersion(version)); err != nil {
			return activateFailure(fmt.Errorf("prepare runtime process switch: %w", err))
		}
		if err := ctx.Err(); err != nil {
			return activateFailure(err)
		}
	}

	// Locked: the pointer exchange. The current link is re-read so the swap
	// reflects whatever is serving right now, not the preamble snapshot.
	swapErr := withMu(func() error {
		current, err := readLink(filepath.Join(dir, "current"))
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		if current != "" && current != safeVersion(version) {
			if err := atomicLink(dir, "previous", current); err != nil {
				return err
			}
			status.Previous = current
		}
		pointerMayHaveChanged = true
		if err := atomicLink(dir, "current", safeVersion(version)); err != nil {
			return err
		}
		return nil
	})
	if swapErr != nil {
		return activateFailure(swapErr)
	}
	// The pointer exchange is the externally visible part of activation. Check
	// cancellation immediately after it as well as during provider checks so a
	// request canceled in this narrow window restores the exact snapshot that
	// was serving before activation began.
	if err := ctx.Err(); err != nil {
		return activateFailure(err)
	}

	// switchAfter refreshes process launch configuration; it waits for config
	// applies and restarts models, so it runs WITHOUT m.mu.
	if switchAfter != nil {
		if err := switchAfter(ctx, name, oldCurrent, safeVersion(version)); err != nil {
			return activateFailure(fmt.Errorf("apply runtime process switch: %w", err))
		}
		if err := ctx.Err(); err != nil {
			return activateFailure(err)
		}
	}

	// Locked: the ACTIVE transition. The durable ledger is re-read fresh — a
	// Pin or removal may have committed while the probes and hooks ran, and
	// writing the stale preamble snapshot would clobber it.
	finalErr := withMu(func() error {
		status.Current = version
		status.Source = manifest.Source
		status.Staged = ""
		status.State = StateActive
		operation.State = StateActive
		operation.Timestamp = m.now()
		if err := m.appendOperation(operation); err != nil {
			return fmt.Errorf("record active runtime transition: %w", err)
		}
		status.LastUpdate = m.now()
		status.LastError = ""
		status.UpdatedAt = m.now()
		state, err := m.statusState(name)
		if err != nil {
			return err
		}
		state.Status = status
		m.setStatusLocked(name, status)
		m.emitProgress(name, "active", 1, "runtime active", nil)
		return m.writeState(name, state)
	})
	if finalErr != nil {
		return activateFailure(finalErr)
	}
	return nil
}

// activationFailure restores the pre-activation pointers and status. The
// caller must hold m.mu. The durable state is re-read fresh: probes and
// hooks run without the lock, so the caller's snapshot may predate ledger
// changes committed in the meantime.
func (m *Manager) activationFailure(name, oldCurrent, oldPrevious string, cause error) error {
	if cause == nil {
		cause = errors.New("runtime activation failed")
	}
	m.emitProgress(name, "rollback", 0, "rolling back failed activation", cause)
	state, err := m.statusState(name)
	if err != nil {
		return fmt.Errorf("activate runtime: %w", errors.Join(cause, fmt.Errorf("read runtime state for rollback: %w", err)))
	}
	status := state.Status
	status.State = StateRollback
	status.LastError = cause.Error()
	status.UpdatedAt = m.now()
	if dir, err := m.runtimeDir(name); err == nil {
		// The candidate is health-checked before current is switched, but an
		// atomic rename or state write can still fail after previous has been
		// updated. Restore both pointers captured at the start of activation;
		// never fall back to an older previous version and silently evict the
		// version that was serving traffic.
		if linkErr := restorePointer(dir, "current", oldCurrent); linkErr != nil {
			status.State = StateDegraded
			status.LastError += "; rollback current: " + linkErr.Error()
		} else if linkErr := restorePointer(dir, "previous", oldPrevious); linkErr != nil {
			status.State = StateDegraded
			status.LastError += "; rollback previous: " + linkErr.Error()
		} else if oldCurrent != "" {
			status.Current = oldCurrent
			status.Previous = oldPrevious
			if manifest, ok := state.Versions[oldCurrent]; ok {
				status.Source = manifest.Source
			}
			status.State = StateActive
		} else {
			// There was no serving runtime before this activation. Once the
			// candidate pointer is removed, there is nothing safe to advertise
			// as active; callers must stage/activate again explicitly.
			status.Current = ""
			status.Previous = ""
			status.Source = ""
			status.State = StateDegraded
		}
	} else {
		status.State = StateDegraded
	}
	rollbackOperation := Operation{ID: operationID(), Name: name, Action: "rollback", Version: oldCurrent, State: status.State, Error: cause.Error(), Timestamp: m.now()}
	var persistenceErrs []error
	if err := m.appendOperation(rollbackOperation); err != nil {
		persistenceErrs = append(persistenceErrs, fmt.Errorf("record activation rollback: %w", err))
	}
	m.setStatusLocked(name, status)
	state.Status = status
	if err := m.writeState(name, state); err != nil {
		persistenceErrs = append(persistenceErrs, fmt.Errorf("persist activation rollback: %w", err))
	}
	return fmt.Errorf("activate runtime: %w", errors.Join(append([]error{cause}, persistenceErrs...)...))
}

// restorePointer restores a manager-owned symlink or removes it when the
// activation snapshot had no pointer. It rejects non-symlink files so a
// rollback cannot delete an operator-owned path.
func restorePointer(dir, name, version string) error {
	path := filepath.Join(dir, name)
	if version == "" {
		info, err := os.Lstat(path)
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink == 0 {
			return fmt.Errorf("runtime pointer %s is not a symlink", name)
		}
		return os.Remove(path)
	}
	return atomicLink(dir, name, version)
}

func (m *Manager) Rollback(ctx context.Context, name string) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	if !m.idleNowFor(name) {
		status := m.statusOrDefault(name, "")
		status.State = StateWaitingForIdle
		status.LastError = "runtime is busy; rollback deferred"
		status.UpdatedAt = m.now()
		m.setStatusLocked(name, status)
		busyErr := fmt.Errorf("%w: runtime %s is busy", ErrRuntimeBusy, name)
		if persistErr := m.persistStatus(name, status, nil); persistErr != nil {
			return errors.Join(busyErr, persistErr)
		}
		return busyErr
	}
	dir, err := m.runtimeDir(name)
	if err != nil {
		return err
	}
	state, err := m.statusState(name)
	if err != nil {
		return err
	}
	if state.Status.Previous == "" {
		return fmt.Errorf("runtime %s has no rollback candidate", name)
	}
	candidateVersion := strings.TrimPrefix(strings.TrimSpace(state.Status.Previous), "versions/")
	manifest, ok := state.Versions[candidateVersion]
	if !ok {
		for version, value := range state.Versions {
			if safeVersion(version) == safeVersion(candidateVersion) {
				manifest, ok = value, true
				candidateVersion = version
				break
			}
		}
	}
	if !ok {
		return fmt.Errorf("runtime %s rollback candidate %s has no manifest", name, candidateVersion)
	}
	provider, ok := m.providers[manifest.Kind]
	if !ok || isNilProvider(provider) {
		return fmt.Errorf("runtime %s: provider %q is not registered", name, manifest.Kind)
	}
	if err := validVersionDir(dir, candidateVersion); err != nil {
		return fmt.Errorf("runtime %s rollback candidate %s is invalid: %w", name, candidateVersion, err)
	}
	oldCurrent, currentErr := readLink(filepath.Join(dir, "current"))
	if currentErr != nil && !errors.Is(currentErr, os.ErrNotExist) {
		return currentErr
	}
	oldPrevious, previousErr := readLink(filepath.Join(dir, "previous"))
	if previousErr != nil && !errors.Is(previousErr, os.ErrNotExist) {
		return previousErr
	}
	switchBefore, switchAfter := m.activationHooks()
	pointerMayHaveChanged := false

	// Record the transition before any pointer changes. A restart can then
	// distinguish a failed rollback from an operator-selected active version.
	status := state.Status
	status.Mode = manifestMode(manifest)
	if m.status == nil {
		m.status = make(map[string]Status)
	}
	previousStatus, hadPreviousStatus := m.status[name]
	restoreStatus := func() {
		if hadPreviousStatus {
			m.setStatusLocked(name, previousStatus)
		} else {
			m.deleteStatusLocked(name)
		}
	}
	operation := Operation{ID: operationID(), Name: name, Action: "rollback", Version: candidateVersion, State: StateRollback, Timestamp: m.now()}
	failRollback := func(cause error) error {
		failure := m.rollbackFailure(name, state, oldCurrent, oldPrevious, operation, cause)
		if !pointerMayHaveChanged || switchAfter == nil {
			return failure
		}
		compensationCtx := context.WithoutCancel(ctx)
		if hookErr := switchAfter(compensationCtx, name, safeVersion(candidateVersion), oldCurrent); hookErr != nil {
			return errors.Join(failure, fmt.Errorf("restore runtime process configuration: %w", hookErr))
		}
		return failure
	}
	status.OperationID = operation.ID
	status.State = StateRollback
	status.LastError = ""
	status.UpdatedAt = m.now()
	m.setStatusLocked(name, status)
	if err := m.appendOperation(operation); err != nil {
		restoreStatus()
		return fmt.Errorf("record runtime rollback transition: %w", err)
	}
	state.Status = status
	if err := m.writeState(name, state); err != nil {
		restoreStatus()
		return fmt.Errorf("persist runtime rollback transition: %w", err)
	}
	m.emitProgress(name, "rollback", 0.1, "verifying rollback candidate", nil)
	candidateDir := filepath.Join(dir, "versions", safeVersion(candidateVersion))
	if err := provider.Verify(ctx, manifest, candidateDir); err != nil {
		return failRollback(err)
	}
	if err := ctx.Err(); err != nil {
		return failRollback(err)
	}
	status.State = StateHealthCheck
	status.UpdatedAt = m.now()
	m.setStatusLocked(name, status)
	m.emitProgress(name, "health_check", 0.5, "checking rollback candidate health", nil)
	if err := provider.Health(ctx, manifest, candidateDir); err != nil {
		return failRollback(err)
	}
	if err := ctx.Err(); err != nil {
		return failRollback(err)
	}
	if switchBefore != nil && oldCurrent != safeVersion(candidateVersion) {
		if err := switchBefore(ctx, name, oldCurrent, safeVersion(candidateVersion)); err != nil {
			return failRollback(fmt.Errorf("prepare runtime process switch: %w", err))
		}
		if err := ctx.Err(); err != nil {
			return failRollback(err)
		}
	}
	m.emitProgress(name, "rollback", 0.75, "switching to rollback candidate", nil)
	pointerMayHaveChanged = true
	if err := atomicLink(dir, "current", safeVersion(candidateVersion)); err != nil {
		return failRollback(err)
	}
	if err := ctx.Err(); err != nil {
		return failRollback(err)
	}
	// Swap the old serving version into previous so a successful rollback can
	// itself be reversed. If there was no current version, remove the stale
	// previous pointer instead of retaining a candidate that is no longer the
	// selected rollback target.
	if oldCurrent != "" {
		if err := atomicLink(dir, "previous", safeVersion(oldCurrent)); err != nil {
			return failRollback(err)
		}
	} else if err := restorePointer(dir, "previous", ""); err != nil {
		return failRollback(err)
	}
	if err := ctx.Err(); err != nil {
		return failRollback(err)
	}
	if switchAfter != nil {
		if err := switchAfter(ctx, name, oldCurrent, safeVersion(candidateVersion)); err != nil {
			return failRollback(fmt.Errorf("apply runtime process switch: %w", err))
		}
		if err := ctx.Err(); err != nil {
			return failRollback(err)
		}
	}
	state.Status.Current = candidateVersion
	state.Status.Previous = oldCurrent
	state.Status.Source = manifest.Source
	state.Status.State = StateActive
	state.Status.LastError = ""
	state.Status.LastUpdate = m.now()
	state.Status.UpdatedAt = m.now()
	operation.State = StateActive
	operation.Timestamp = m.now()
	m.setStatusLocked(name, state.Status)
	if err := m.appendOperation(operation); err != nil {
		return failRollback(fmt.Errorf("record active runtime transition: %w", err))
	}
	m.emitProgress(name, "active", 1, "runtime rollback completed", nil)
	if err := m.writeState(name, state); err != nil {
		// State persistence is part of the transaction boundary. Restore the
		// exact pointer snapshot rather than leaving a serving runtime whose
		// metadata describes a different version after restart.
		return failRollback(err)
	}
	return nil
}

// rollbackFailure restores the exact current/previous pointer snapshot when a
// candidate fails verification, health, pointer exchange, or state
// persistence. The old current remains the serving version whenever possible;
// a degraded state is reported only if restoration itself fails.
func (m *Manager) rollbackFailure(name string, state persistedState, oldCurrent, oldPrevious string, operation Operation, cause error) error {
	if cause == nil {
		cause = errors.New("runtime rollback failed")
	}
	m.emitProgress(name, "rollback", 0, "rollback candidate rejected", cause)
	status := state.Status
	status.LastError = cause.Error()
	status.State = StateRollback
	if dir, err := m.runtimeDir(name); err == nil {
		currentErr := restorePointer(dir, "current", oldCurrent)
		previousErr := restorePointer(dir, "previous", oldPrevious)
		if currentErr != nil || previousErr != nil {
			status.State = StateDegraded
			if currentErr != nil {
				status.LastError += "; rollback current: " + currentErr.Error()
			}
			if previousErr != nil {
				status.LastError += "; rollback previous: " + previousErr.Error()
			}
		} else if oldCurrent != "" {
			status.Current = oldCurrent
			status.Previous = oldPrevious
			if manifest, ok := state.Versions[oldCurrent]; ok {
				status.Source = manifest.Source
			}
			status.State = StateActive
		} else {
			status.Current = ""
			status.Previous = ""
			status.Source = ""
			status.State = StateDegraded
		}
	} else {
		status.State = StateDegraded
	}
	operation.State = status.State
	operation.Error = cause.Error()
	operation.Timestamp = m.now()
	var persistenceErrs []error
	if err := m.appendOperation(operation); err != nil {
		persistenceErrs = append(persistenceErrs, fmt.Errorf("record runtime rollback failure: %w", err))
	}
	status.UpdatedAt = m.now()
	m.setStatusLocked(name, status)
	state.Status = status
	if err := m.writeState(name, state); err != nil {
		persistenceErrs = append(persistenceErrs, fmt.Errorf("persist runtime rollback failure: %w", err))
	}
	return fmt.Errorf("rollback runtime: %w", errors.Join(append([]error{cause}, persistenceErrs...)...))
}

func (m *Manager) Pin(name, version string) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	if err := validateVersion(version); err != nil {
		return err
	}
	state, err := m.statusState(name)
	if err != nil {
		return err
	}
	if _, ok := state.Versions[version]; !ok {
		return fmt.Errorf("runtime %s version %s is not installed", name, version)
	}
	previousStatus, hadStatus := m.status[name]
	state.Status.Pinned = version
	state.Status.UpdatedAt = m.now()
	m.setStatusLocked(name, state.Status)
	if err := m.writeState(name, state); err != nil {
		if hadStatus {
			m.setStatusLocked(name, previousStatus)
		} else {
			m.deleteStatusLocked(name)
		}
		return err
	}
	return nil
}

func (m *Manager) Unpin(name string) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	state, err := m.statusState(name)
	if err != nil {
		return err
	}
	previousStatus, hadStatus := m.status[name]
	state.Status.Pinned = ""
	state.Status.UpdatedAt = m.now()
	m.setStatusLocked(name, state.Status)
	if err := m.writeState(name, state); err != nil {
		if hadStatus {
			m.setStatusLocked(name, previousStatus)
		} else {
			m.deleteStatusLocked(name)
		}
		return err
	}
	return nil
}

func (m *Manager) statusOrDefault(name, kind string) Status {
	status := m.status[name]
	if status.Name == "" {
		status = Status{Name: name, Kind: kind, State: StateIdle, UpdatedAt: m.now()}
	}
	if status.Kind == "" {
		status.Kind = kind
	}
	return status
}

func (m *Manager) persistStatus(name string, status Status, versions map[string]Manifest) error {
	state, err := m.statusState(name)
	if err != nil {
		return err
	}
	state.Status = status
	if versions != nil {
		state.Versions = versions
	}
	return m.writeState(name, state)
}

func (m *Manager) RemoveVersion(name, version string) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	if err := validateVersion(version); err != nil {
		return err
	}
	dir, err := m.runtimeDir(name)
	if err != nil {
		return err
	}
	state, err := m.statusState(name)
	if err != nil {
		return err
	}
	if state.Status.Current == version || state.Status.Previous == version || state.Status.Pinned == version {
		return fmt.Errorf("%w: runtime %s version %s is still referenced", ErrVersionProtected, name, version)
	}
	if protected, reason := m.versionProtected(name, version); protected {
		if strings.TrimSpace(reason) == "" {
			reason = "runtime has an active reference"
		}
		return fmt.Errorf("%w: runtime %s version %s: %s", ErrVersionProtected, name, version, reason)
	}
	if err := validVersionDir(dir, version); err != nil {
		return fmt.Errorf("runtime %s version %s is not installed: %w", name, version, err)
	}
	if err := os.RemoveAll(filepath.Join(dir, "versions", safeVersion(version))); err != nil {
		return err
	}
	delete(state.Versions, version)
	if state.Status.Staged == version {
		state.Status.Staged = ""
	}
	if state.Status.Available == version {
		state.Status.Available = ""
	}
	if state.Status.Name == "" {
		state.Status.Name = name
	}
	state.Status.UpdatedAt = m.now()
	if err := m.writeState(name, state); err != nil {
		return err
	}
	m.setStatusLocked(name, state.Status)
	return nil
}

func syncDir(path string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return f.Sync()
}

func operationID() string { return fmt.Sprintf("op-%d", time.Now().UnixNano()) }

func (m *Manager) appendOperation(operation Operation) error {
	if m == nil {
		return errors.New("runtime manager is nil")
	}
	dir, err := m.runtimeDir(operation.Name)
	if err != nil {
		return err
	}
	if err := withFileLock(filepath.Join(m.root, ".manager.lock"), func() error {
		return appendOperationUnlocked(dir, operation)
	}); err != nil {
		return err
	}
	m.operationMu.RLock()
	sink := m.operationSink
	m.operationMu.RUnlock()
	if sink != nil {
		sink(operation)
	}
	return nil
}

func appendOperationUnlocked(dir string, operation Operation) error {
	if err := rejectSymlinkPath(dir); err != nil {
		return fmt.Errorf("runtime operation directory: %w", err)
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	operationPath := filepath.Join(dir, "operations.jsonl")
	if err := rejectSymlinkPath(operationPath); err != nil {
		return fmt.Errorf("runtime operation journal path: %w", err)
	}
	data, err := json.Marshal(operation)
	if err != nil {
		return err
	}
	f, err := os.OpenFile(operationPath, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o640)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := f.Write(append(data, '\n')); err != nil {
		return err
	}
	return f.Sync()
}

func readOperations(path string) ([]Operation, error) {
	if err := rejectSymlinkPath(path); err != nil {
		return nil, fmt.Errorf("runtime operation journal path: %w", err)
	}
	file, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	defer file.Close()

	// A runtime can append one small JSON record for every state transition for
	// months. Detail only exposes the most recent 100 records, so never read an
	// unbounded journal into memory. Seeking to a bounded tail keeps the
	// response useful even when an old journal has grown unexpectedly large.
	const (
		maxJournalBytes = 8 << 20
		maxRecordBytes  = 256 << 10
	)
	if info, statErr := file.Stat(); statErr != nil {
		return nil, statErr
	} else if info.Size() > maxJournalBytes {
		offset := info.Size() - maxJournalBytes
		if _, seekErr := file.Seek(offset, io.SeekStart); seekErr != nil {
			return nil, seekErr
		}
		// The seek may land in the middle of a record. Inspect the byte immediately
		// before the selected tail so an exact record boundary is preserved; only
		// discard a prefix when the offset really points into a JSON line.
		discardPrefix := offset == 0
		if offset > 0 {
			var previous [1]byte
			read, readErr := file.ReadAt(previous[:], offset-1)
			if readErr != nil && !(errors.Is(readErr, io.EOF) && read == 1) {
				return nil, readErr
			}
			discardPrefix = read != 1 || previous[0] != '\n'
		}
		reader := bufio.NewReaderSize(file, 32<<10)
		if discardPrefix {
			_, readErr := reader.ReadString('\n')
			if readErr != nil && !errors.Is(readErr, io.EOF) {
				return nil, readErr
			}
			if errors.Is(readErr, io.EOF) {
				// There was no complete record boundary in the selected tail. Rewind
				// so the bounded record reader can still report a genuinely oversized
				// unterminated record instead of silently dropping the whole tail.
				if _, seekErr := file.Seek(offset, io.SeekStart); seekErr != nil {
					return nil, seekErr
				}
				reader = bufio.NewReaderSize(file, 32<<10)
			}
		}
		return readOperationsFrom(reader, maxRecordBytes)
	}
	return readOperationsFrom(bufio.NewReaderSize(file, 32<<10), maxRecordBytes)
}

func readOperationsFrom(reader *bufio.Reader, maxRecordBytes int) ([]Operation, error) {
	if reader == nil {
		return nil, errors.New("runtime operation journal reader is nil")
	}
	operations := make([]Operation, 0, 100)
	for {
		line, err := readJournalLine(reader, maxRecordBytes)
		trimmed := strings.TrimSpace(line)
		if trimmed != "" {
			var operation Operation
			if decodeErr := json.Unmarshal([]byte(trimmed), &operation); decodeErr != nil {
				// A process can be terminated during the single append write. A
				// malformed unterminated final line is therefore treated as an
				// incomplete record; malformed lines terminated by '\n' remain an
				// explicit journal corruption error.
				if errors.Is(err, io.EOF) {
					break
				}
				return nil, fmt.Errorf("decode runtime operation journal: %w", decodeErr)
			}
			operations = append(operations, operation)
			if len(operations) > 100 {
				operations = operations[len(operations)-100:]
			}
		}
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, err
		}
	}
	return operations, nil
}

func readJournalLine(reader *bufio.Reader, maxRecordBytes int) (string, error) {
	if maxRecordBytes < 1 {
		maxRecordBytes = 256 << 10
	}
	var line []byte
	for {
		part, err := reader.ReadSlice('\n')
		line = append(line, part...)
		if len(line) > maxRecordBytes {
			return "", fmt.Errorf("runtime operation journal record exceeds %d bytes", maxRecordBytes)
		}
		if err == nil {
			return string(line), nil
		}
		if errors.Is(err, bufio.ErrBufferFull) {
			continue
		}
		if errors.Is(err, io.EOF) {
			return string(line), io.EOF
		}
		return string(line), err
	}
}

func writeManifest(directory string, manifest Manifest) error {
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	if int64(len(data)) > maxRuntimeManifestBytes {
		return fmt.Errorf("runtime manifest exceeds %d bytes", maxRuntimeManifestBytes)
	}
	return writeAtomicFile(filepath.Join(directory, "manifest.json"), data, 0o640)
}

// writeAtomicFile persists small runtime metadata files without exposing a
// partially-written JSON document after a process or host crash. The temporary
// file lives beside the target so rename is atomic on the same filesystem;
// both the file and containing directory are synced before returning.
func writeAtomicFile(path string, data []byte, mode os.FileMode) error {
	directory := filepath.Dir(path)
	if err := rejectSymlinkPath(path); err != nil {
		return fmt.Errorf("runtime metadata path: %w", err)
	}
	if err := rejectSymlinkPath(directory); err != nil {
		return fmt.Errorf("runtime metadata directory: %w", err)
	}
	tmp, err := os.CreateTemp(directory, ".atomic-*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if err := tmp.Chmod(mode); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, path); err != nil {
		return err
	}
	return syncDir(directory)
}

func readManifest(path string) (Manifest, error) {
	if err := rejectSymlinkPath(path); err != nil {
		return Manifest{}, fmt.Errorf("runtime manifest path: %w", err)
	}
	file, err := os.Open(path)
	if err != nil {
		return Manifest{}, err
	}
	defer file.Close()
	data, err := io.ReadAll(io.LimitReader(file, maxRuntimeManifestBytes+1))
	if err != nil {
		return Manifest{}, err
	}
	if int64(len(data)) > maxRuntimeManifestBytes {
		return Manifest{}, fmt.Errorf("runtime manifest exceeds %d bytes", maxRuntimeManifestBytes)
	}
	var manifest Manifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		return Manifest{}, err
	}
	return manifest, nil
}

func readLink(path string) (string, error) {
	target, err := os.Readlink(path)
	if err != nil {
		return "", err
	}
	clean := filepath.Clean(target)
	if filepath.IsAbs(clean) || filepath.Dir(clean) != "versions" || filepath.Base(clean) == "." || filepath.Base(clean) == ".." {
		return "", errors.New("runtime pointer targets outside its versions directory")
	}
	if err := validateName(filepath.Base(clean)); err != nil {
		return "", err
	}
	return filepath.Base(clean), nil
}

func atomicLink(dir, name, version string) error {
	return withFileLock(filepath.Join(dir, ".manager.lock"), func() error {
		return atomicLinkUnlocked(dir, name, version)
	})
}

func atomicLinkUnlocked(dir, name, version string) error {
	if err := rejectSymlinkPath(dir); err != nil {
		return fmt.Errorf("runtime pointer directory: %w", err)
	}
	if err := validateName(version); err != nil {
		return err
	}
	if err := validVersionDir(dir, version); err != nil {
		return fmt.Errorf("runtime pointer target %s is invalid: %w", version, err)
	}
	tmp := filepath.Join(dir, fmt.Sprintf(".%s-%d", name, time.Now().UnixNano()))
	if err := os.Symlink(filepath.Join("versions", version), tmp); err != nil {
		return err
	}
	destination := filepath.Join(dir, name)
	if info, err := os.Lstat(destination); err == nil && info.Mode()&os.ModeSymlink == 0 {
		_ = os.Remove(tmp)
		return fmt.Errorf("runtime pointer %s is not a symlink", name)
	}
	if err := os.Rename(tmp, destination); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return syncDir(dir)
}

// validVersionDir rejects a version directory that is missing or is itself a
// symlink. Runtime pointers are allowed to reference only manager-owned
// immutable directories below <runtime>/versions; following a symlink here
// would let a crafted current/previous pointer escape that boundary.
func validVersionDir(runtimeDir, version string) error {
	if err := rejectSymlinkPath(runtimeDir); err != nil {
		return fmt.Errorf("runtime directory: %w", err)
	}
	if err := validateName(version); err != nil {
		return err
	}
	versionsDir := filepath.Join(runtimeDir, "versions")
	if info, err := os.Lstat(versionsDir); err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		if err != nil {
			return err
		}
		return errors.New("versions directory is not a real directory")
	}
	path := filepath.Join(versionsDir, safeVersion(version))
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return errors.New("version is not a real directory")
	}
	resolvedVersions, err := filepath.EvalSymlinks(versionsDir)
	if err != nil {
		return err
	}
	resolvedPath, err := filepath.EvalSymlinks(path)
	if err != nil {
		return err
	}
	rel, err := filepath.Rel(resolvedVersions, resolvedPath)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return errors.New("version path escapes versions directory")
	}
	return nil
}

// CopyProvider is useful for bundled fallback seeding and local test/runtime
// artifacts. It copies a directory without following symlinks outside source.
type CopyProvider struct{}

func (CopyProvider) Stage(ctx context.Context, spec Spec, destination string) (Manifest, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return Manifest{}, err
	}
	source := strings.TrimSpace(spec.Source)
	if source == "" {
		return Manifest{}, errors.New("copy runtime source is required")
	}
	info, err := os.Lstat(source)
	if err != nil {
		return Manifest{}, err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return Manifest{}, errors.New("copy runtime source must not be a symlink")
	}
	if !info.IsDir() {
		return Manifest{}, errors.New("copy runtime source must be a directory")
	}
	if destination == "" {
		return Manifest{}, errors.New("copy runtime destination is required")
	}
	destinationInfo, err := os.Lstat(destination)
	if err != nil {
		return Manifest{}, err
	}
	if destinationInfo.Mode()&os.ModeSymlink != 0 || !destinationInfo.IsDir() {
		return Manifest{}, errors.New("copy runtime destination must be a real directory")
	}
	if err := copyTree(ctx, source, destination); err != nil {
		return Manifest{}, err
	}
	return Manifest{Name: spec.Name, Version: spec.Version, Kind: spec.Kind, Source: source, Ref: spec.Ref, Commit: spec.Commit, Checksum: spec.Checksum, Metadata: spec.Metadata, InstalledAt: time.Now()}, nil
}

func (CopyProvider) Verify(ctx context.Context, _ Manifest, directory string) error {
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	info, err := os.Lstat(directory)
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return errors.New("staged runtime is not a directory")
	}
	return nil
}

func (CopyProvider) Health(ctx context.Context, manifest Manifest, directory string) error {
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	if manifest.Name == "" || directory == "" {
		return errors.New("runtime health check received empty identity")
	}
	return nil
}

func copyTree(ctx context.Context, source, destination string) error {
	if ctx == nil {
		ctx = context.Background()
	}
	if source == "" || destination == "" {
		return errors.New("copy tree source and destination are required")
	}
	if err := rejectSymlinkPath(source); err != nil {
		return fmt.Errorf("copy tree source: %w", err)
	}
	if err := rejectSymlinkPath(destination); err != nil {
		return fmt.Errorf("copy tree destination: %w", err)
	}
	if info, err := os.Lstat(source); err != nil {
		return err
	} else if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return errors.New("copy tree source must be a real directory")
	}
	if info, err := os.Lstat(destination); err != nil {
		return err
	} else if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return errors.New("copy tree destination must be a real directory")
	}
	return filepath.Walk(source, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		rel, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		target := filepath.Join(destination, rel)
		if info.Mode()&os.ModeSymlink != 0 {
			link, err := os.Readlink(path)
			if err != nil {
				return err
			}
			cleanLink := filepath.Clean(link)
			if filepath.IsAbs(link) || cleanLink == ".." || strings.HasPrefix(cleanLink, ".."+string(os.PathSeparator)) {
				return fmt.Errorf("runtime source symlink escapes source: %s", path)
			}
			return os.Symlink(link, target)
		}
		if info.IsDir() {
			if existing, statErr := os.Lstat(target); statErr == nil {
				if existing.Mode()&os.ModeSymlink != 0 || !existing.IsDir() {
					return fmt.Errorf("copy tree target is not a real directory: %s", target)
				}
			} else if !errors.Is(statErr, os.ErrNotExist) {
				return statErr
			}
			return os.MkdirAll(target, info.Mode().Perm())
		}
		if existing, statErr := os.Lstat(target); statErr == nil {
			if existing.Mode()&os.ModeSymlink != 0 || !existing.Mode().IsRegular() {
				return fmt.Errorf("copy tree target is not a regular file: %s", target)
			}
		} else if !errors.Is(statErr, os.ErrNotExist) {
			return statErr
		}
		in, err := os.Open(path)
		if err != nil {
			return err
		}
		defer in.Close()
		out, err := os.OpenFile(target, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, info.Mode().Perm())
		if err != nil {
			return err
		}
		_, copyErr := io.Copy(out, in)
		syncErr := out.Sync()
		closeErr := out.Close()
		return errors.Join(copyErr, syncErr, closeErr)
	})
}
