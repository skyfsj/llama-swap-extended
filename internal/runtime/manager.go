// ErrVersionProtected is returned when a version is still referenced by the
// manager or by the embedding server. Callers can map this to a conflict
// instead of presenting a destructive-operation failure as a generic bad
// request.
var ErrVersionProtected = errors.New("runtime version is protected")

// ErrRuntimeBusy identifies an idle-gate refusal. Callers can distinguish a
// normal operational race (for example, an LMCache model reference arriving
// during activation) from a provider/build failure and keep the candidate in
// WAITING_FOR_IDLE instead of misreporting it as DEGRADED.
var ErrRuntimeBusy = errors.New("runtime is busy")

